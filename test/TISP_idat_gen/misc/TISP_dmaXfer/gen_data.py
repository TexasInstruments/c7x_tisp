"""Generate TISP_dmaXfer_idat.h, TISP_dmaXfer_idat.cpp, and
TISP_dmaXfer_memory_map.hpp from test_cases_list.csv.

CSV columns:
  testID   - integer test identifier
  numReps  - warm-loop repetition count
  sizes    - bracket-array of byte sizes, e.g. [32768,8192]
  dirs     - bracket-array of directions,  e.g. [S,L]
  w        - DMA window mode: 1=sequential, 2=evict-then-parallel-loads (default 1)

n (number of transfers) is derived from len(sizes).
Slot assignment: within each case, xfer i gets ddrSlot=i, l2Slot=i.
Global pool sizes:
  N_EXT_SLOTS    = max(n) across all cases
  MAX_SLOT_BYTES = max(sizes) across all transfers, rounded up to 128 B

The external memory (EXT) is selected at compile time:
  SOC_AM275X  -> extBuffer placed in .hyperRamData  (HyperRAM via FSS1)
  other       -> extBuffer placed in .ddrData        (DDR / OCRAM)
"""

from __future__ import print_function
import csv
import os

MAX_TRANSFERS = 8
ALIGN = 128


def parse_array(s):
    """Parse '[a,b,c]' -> ['a','b','c']"""
    return [x.strip() for x in s.strip().strip("[]").split(",") if x.strip()]


def align_up(val, align):
    return ((val + align - 1) // align) * align


def load_test_cases(csv_path):
    cases = []
    with open(csv_path, encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            test_id  = int(row["testID"].strip())
            num_reps = int(row["numReps"].strip())
            sizes    = [int(x) for x in parse_array(row["sizes"])]
            dirs     = [x.upper() for x in parse_array(row["dirs"])]
            w        = int(row.get("w", "1").strip())
            assert len(sizes) == len(dirs), \
                f"testID {test_id}: sizes/dirs length mismatch"
            assert len(sizes) <= MAX_TRANSFERS, \
                f"testID {test_id}: n={len(sizes)} exceeds MAX_TRANSFERS={MAX_TRANSFERS}"
            for s in sizes:
                assert s % 4 == 0, \
                    f"testID {test_id}: size {s} not a multiple of sizeof(float)"
            assert w in (1, 2), \
                f"testID {test_id}: w={w} invalid, must be 1 or 2"
            if w == 2:
                assert len(sizes) == 3 and dirs[0] == 'S', \
                    f"testID {test_id}: W=2 requires n=3 with dirs[0]='S' (evict)"
            cases.append({"testID": test_id, "numReps": num_reps,
                           "sizes": sizes, "dirs": dirs, "n": len(sizes), "w": w})
    return cases


def compute_pool_params(cases):
    max_n          = max(c["n"] for c in cases)
    max_size       = max(s for c in cases for s in c["sizes"])
    max_slot_bytes = align_up(max_size, ALIGN)
    return max_n, max_slot_bytes


def write_idat_h(path, cases):
    with open(path, "w") as f:
        f.write("/* This file is autogenerated by gen_data.py — do not edit */\n")
        f.write("#pragma once\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define TISP_DMAXFER_MAX_TRANSFERS {MAX_TRANSFERS}U\n\n")
        f.write("#ifdef __cplusplus\n")
        f.write('extern "C" {\n')
        f.write("#endif\n\n")
        f.write("typedef struct {\n")
        f.write("   uint32_t testID;\n")
        f.write("   uint32_t n;\n")
        f.write(f"   uint32_t sizes[TISP_DMAXFER_MAX_TRANSFERS]; /* bytes per transfer */\n")
        f.write(f"   char     dirs[TISP_DMAXFER_MAX_TRANSFERS];  /* 'S' store L2->ext, 'L' load ext->L2 */\n")
        f.write(f"   uint32_t ddrSlot[TISP_DMAXFER_MAX_TRANSFERS];\n")
        f.write(f"   uint32_t l2Slot[TISP_DMAXFER_MAX_TRANSFERS];\n")
        f.write("   uint32_t numReps;\n")
        f.write("   uint32_t w;        /* DMA window mode: 1=sequential, 2=evict-then-parallel-loads */\n")
        f.write("} TISP_dmaXfer_testParams_t;\n\n")
        f.write("void TISP_dmaXfer_getTestParams(TISP_dmaXfer_testParams_t **params,\n")
        f.write("                               int32_t                   *numTests);\n\n")
        f.write("#ifdef __cplusplus\n")
        f.write("}\n")
        f.write("#endif\n")


def write_idat_cpp(path, cases):
    with open(path, "w") as f:
        f.write("/* This file is autogenerated by gen_data.py — do not edit */\n")
        f.write('#include "TISP_dmaXfer_idat.h"\n\n')
        f.write("static TISP_dmaXfer_testParams_t testParams[] = {\n")
        for c in cases:
            n     = c["n"]
            sizes = c["sizes"] + [0] * (MAX_TRANSFERS - n)
            dirs  = c["dirs"]  + ['\0'] * (MAX_TRANSFERS - n)
            slots = list(range(n)) + [0] * (MAX_TRANSFERS - n)

            sizes_str = ", ".join(str(s) for s in sizes)
            dirs_str  = ", ".join(f"'{d}'" if d else "'\\0'" for d in dirs)
            slots_str = ", ".join(str(s) for s in slots)

            f.write("   {\n")
            f.write(f"      {c['testID']},                    /* testID */\n")
            f.write(f"      {n}U,                             /* n */\n")
            f.write(f"      {{ {sizes_str} }},  /* sizes */\n")
            f.write(f"      {{ {dirs_str} }}, /* dirs */\n")
            f.write(f"      {{ {slots_str} }},  /* ddrSlot */\n")
            f.write(f"      {{ {slots_str} }},  /* l2Slot */\n")
            f.write(f"      {c['numReps']}U,                  /* numReps */\n")
            f.write(f"      {c['w']}U,                       /* w */\n")
            f.write("   },\n")
        f.write("};\n\n")
        f.write("void TISP_dmaXfer_getTestParams(TISP_dmaXfer_testParams_t **params,\n")
        f.write("                               int32_t                   *numTests)\n")
        f.write("{\n")
        f.write("   *params   = testParams;\n")
        f.write("   *numTests = (int32_t)(sizeof(testParams) / sizeof(TISP_dmaXfer_testParams_t));\n")
        f.write("}\n")


def write_memory_map(path, n_slots, max_slot_bytes):
    slot_total    = n_slots * max_slot_bytes
    ref_total     = 2 * n_slots * max_slot_bytes   # ref_store + ref_load

    with open(path, "w") as f:
        f.write("/* This file is autogenerated by gen_data.py — do not edit */\n")
        f.write("#pragma once\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define MAX_SLOT_BYTES  {max_slot_bytes}U\n")
        f.write(f"#define N_EXT_SLOTS     {n_slots}U\n")
        f.write(f"#define N_L2_SLOTS      {n_slots}U\n\n")
        f.write(f"/* slot_total={slot_total} B per variant,  ref_total={ref_total} B */\n\n")

        # Buffer declarations — AM275 has two variants (OCRAM + HyperRAM)
        f.write("#if defined(HOST_EMULATION)\n")
        f.write(f"static uint8_t extBuffer   [{slot_total}U];\n")
        f.write(f"static uint8_t extRefBuffer[{ref_total}U];\n")
        f.write(f"static uint8_t l2Buffer    [{slot_total}U];\n")
        f.write("#elif defined(SOC_AM275X)\n")
        f.write(f'/* OCRAM variant — DMA from/to OCRAM */\n')
        f.write(f'__attribute__((section(".ddrData"),      aligned(128))) uint8_t ocramBuffer  [{slot_total}U];\n')
        f.write(f'/* HyperRAM variant — DMA from/to HyperRAM */\n')
        f.write(f'__attribute__((section(".hyperRamData"), aligned(128))) uint8_t hyperRamBuffer[{slot_total}U];\n')
        f.write(f'/* Refs always in HyperRAM to keep OCRAM free for code */\n')
        f.write(f'__attribute__((section(".hyperRamData"), aligned(128))) uint8_t extRefBuffer[{ref_total}U];\n')
        f.write(f'__attribute__((section(".l2sramData"),   aligned(128))) uint8_t l2Buffer    [{slot_total}U];\n')
        f.write("#else\n")
        f.write(f'__attribute__((section(".ddrData"),    aligned(128))) uint8_t extBuffer   [{slot_total}U];\n')
        f.write(f'__attribute__((section(".ddrData"),    aligned(128))) uint8_t extRefBuffer[{ref_total}U];\n')
        f.write(f'__attribute__((section(".l2sramData"), aligned(128))) uint8_t l2Buffer    [{slot_total}U];\n')
        f.write("#endif\n\n")

        # Variant table — drives the outer test loop
        f.write("typedef struct { uint8_t *extBuf; const char *name; } TispDmaExtVariant;\n\n")
        f.write("#if defined(HOST_EMULATION) || !defined(SOC_AM275X)\n")
        f.write("static TispDmaExtVariant gExtVariants[] = { {extBuffer, \"DDR\"} };\n")
        f.write("#else\n")
        f.write("static TispDmaExtVariant gExtVariants[] = {\n")
        f.write("    {ocramBuffer,    \"OCRAM\"},\n")
        f.write("    {hyperRamBuffer, \"HyperRAM\"},\n")
        f.write("};\n")
        f.write("#endif\n")
        f.write("#define N_EXT_VARIANTS ((int)(sizeof(gExtVariants) / sizeof(gExtVariants[0])))\n\n")

        # Address macros — EXT_ADDR takes the variant base pointer
        f.write("/* EXT_ADDR takes the variant base pointer from gExtVariants[vi].extBuf */\n")
        f.write("#define EXT_ADDR(base, i)      ((base)       + (i) * MAX_SLOT_BYTES)\n")
        f.write("#define REF_STORE_EXT_ADDR(i)  (extRefBuffer + (i) * MAX_SLOT_BYTES)\n")
        f.write("#define REF_LOAD_EXT_ADDR(i)   (extRefBuffer + N_EXT_SLOTS * MAX_SLOT_BYTES + (i) * MAX_SLOT_BYTES)\n")
        f.write("#define L2_ADDR(i)             (l2Buffer     + (i) * MAX_SLOT_BYTES)\n")


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    csv_path   = os.path.join(script_dir, "test_cases_list.csv")
    out_dir    = os.path.join(script_dir, "../../../misc/TISP_dmaXfer")

    cases = load_test_cases(csv_path)
    n_slots, max_slot_bytes = compute_pool_params(cases)

    print(f"  test cases    : {len(cases)}")
    print(f"  N_EXT_SLOTS   : {n_slots}")
    print(f"  MAX_SLOT_BYTES: {max_slot_bytes}")

    write_idat_h(    os.path.join(out_dir, "TISP_dmaXfer_idat.h"),          cases)
    write_idat_cpp(  os.path.join(out_dir, "TISP_dmaXfer_idat.cpp"),        cases)
    write_memory_map(os.path.join(out_dir, "TISP_dmaXfer_memory_map.hpp"),
                     n_slots, max_slot_bytes)
    print("Done.")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--allCases", action="store_true", help="generate all cases (default)")
    ap.parse_args()   # accept -a flag passed by gen_all_test_case_headers.sh
    main()
