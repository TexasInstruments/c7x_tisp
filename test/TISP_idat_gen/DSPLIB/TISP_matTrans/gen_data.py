from __future__ import print_function
from subprocess import call
from sys import platform

import sys
import numpy as np
import csv

sys.path.append("../../common")
import TISP_utils
import file_io
import matTrans

# C dtype names of the CSV -> numpy dtype names
_NP_DTYPES = {"float": "float32", "double": "float64"}

# TISP MatTrans supports float and double
DSPLIB_DTYPES = {"float": "DSPLIB_FLOAT32", "double": "DSPLIB_FLOAT64"}


def gen_testCaseParams(idatFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        idatFile (file object): Input file object to idat.c file
        currPrm (dict object): Dict object with test case parameter

    """

    testType = currPrm["testType"]
    dType = currPrm["dType"]
    dimX = currPrm["dimX"]
    dimY = currPrm["dimY"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    numBlocks = currPrm["numBlocks"]
    outputDataLocation = currPrm["outputDataLocation"]
    testId = currPrm["ID"]

    if testType == "STATIC":
        inputData = "staticRefInCase" + str(testId)
        outputData = "staticRefOutCase" + str(testId)
    else:
        inputData = "NULL"
        outputData = "NULL"

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % testType)
    idatFile.write("%s, // staticIn \n" % inputData)
    idatFile.write("%s, // staticOut \n" % outputData)
    idatFile.write("%s, // dataType \n" % DSPLIB_DTYPES[dType])
    idatFile.write("%d, // widthIn (dimX) \n" % dimX)
    idatFile.write("%d, // heightIn (dimY) \n" % dimY)
    idatFile.write(
        "DSPLIB_CALC_STRIDE(%d * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES), // strideIn (bytes)\n"
        % (dimX, dType)
    )
    idatFile.write("%d, // widthOut \n" % dimY)
    idatFile.write("%d, // heightOut \n" % dimX)
    idatFile.write(
        "DSPLIB_CALC_STRIDE(%d * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES), // strideOut (bytes)\n"
        % (dimY, dType)
    )
    idatFile.write("%d, // numBlocks \n" % numBlocks)
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif")
    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        idatFile (file object): Input file object to idat.c file
        testCases (list): List of dict objects with test case parameters

    """

    fIn = open("../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    idatFile.write('#include "TISP_matTrans_idat.h"')
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_matTrans_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()
    fIn.close()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        testCase (dict): Dictionary object with test case parameters

    Returns:
        dict: Dictionary object with necessary parameters converted to int

    """

    testCase["dimX"] = int(testCase["dimX"])
    testCase["dimY"] = int(testCase["dimY"])
    testCase["numReps"] = int(testCase["numReps"])
    testCase["numBlocks"] = int(testCase["numBlocks"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input and output matrices
    into a header file usable in C/C++ code.

    Args:
        testCase (dict): A dict object with all the test case parameters

    Returns:
        [float float]: Minimum and maximum value in output matrix

    """

    testId = testCase["ID"]
    dType = testCase["dType"]
    dimX = testCase["dimX"]
    dimY = testCase["dimY"]

    numBlocks = testCase["numBlocks"]

    # Build the model with the case's values. The case runs numBlocks independent matrices back to
    # back: the blocks are stacked one after the other (input: numBlocks * dimY rows, output:
    # numBlocks * dimX rows), each block transposed on its own.
    algo = matTrans.MatTrans(
        rows=dimY, cols=dimX, in_dtype=_NP_DTYPES[dType], num_blocks=numBlocks
    )
    inputMatrix = algo.generate_inputs()

    # exec() transposes one block: run the blocks back to back
    outputMatrix = np.vstack(
        [
            algo.exec(inputMatrix[blk * dimY : (blk + 1) * dimY, :])
            for blk in range(numBlocks)
        ]
    )

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(inputMatrix, outputMatrix, testCase, headerFileName)

    return [np.min(outputMatrix), np.max(outputMatrix)]


# CSV file with paratmeters for all test cases
testCasesCsvFile = "test_cases_list.csv"
testIdList = []  # list of test IDs that we want to generate test data
testIdList += range(1, 46)

myArgs = TISP_utils.getCmdLineArgs()


def gen_test_case(testCase):
    if testCase["testType"] == "STATIC":
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as tesType is RANDOM",
        )


#############################################################################
# Open CSV file with test cases and generate header file with test data for #
# test cases of interest; based on testIdList                               #
#############################################################################

with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)

    for testCase in testCases:
        testCase = process_test_case(testCase)

    for testCase in testCases:
        if myArgs.allCases == True:
            gen_test_case(testCase)
        elif int(testCase["ID"]) in testIdList:
            gen_test_case(testCase)


idatFileName = "../../../DSPLIB/TISP_matTrans/TISP_matTrans_idat.c"

##########################################################################
# Generate idat.c file by parsing all the test cases in the CSV file     #
##########################################################################


with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)


if platform == "linux" or platform == "linux2":
    call(["clang-format", "-style=file", "-i", idatFileName])
    call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
    call(["rm", "-f", idatFileName + "~"])  # remove backup file


print("Idat file generation completed")
