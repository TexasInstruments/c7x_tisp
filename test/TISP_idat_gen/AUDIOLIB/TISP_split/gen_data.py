def gen_testCaseParams(idatFile, currPrm):

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    totalInputChannels = int(currPrm["totalInputChannels"])  
    inSamples = currPrm["samples"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    numOutputs = int(currPrm["numOutputs"])
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]
    strideInElements = currPrm["strideInElements"]
    strideOutElements = currPrm["strideOutElements"]

    C7100 = currPrm["C7100"]


    if testType == "STATIC":
        in0 = "staticRefInCase" + testId
        out0 = ["staticRefOut" + str(idx) + "Case" + testId for idx in range(numOutputs)]
    else:
        in0="NULL"
        out0=["NULL" for _ in range(numOutputs)]

    if C7100 == "FALSE":
        idatFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Input buffer\n" % ((in0)))

    # Format output buffer as pointer to static array
    if testType == "STATIC":
        out0_formatted = "(void**)staticOutPtrsCase" + testId
    else:
        out0_formatted = "NULL"
    idatFile.write("%s, // Output buffer \n" % (out0_formatted))

    idatFile.write("%s, // inSamples (S = %d samples per channel)\n" % ((inSamples), int(inSamples)))
    idatFile.write("%s, // totalInputChannels (C_total = %d channels from input)\n" % (totalInputChannels, totalInputChannels))
    if testType == "STATIC":
        outChannelsArrayName = "outChannelsCase" + testId
    else:
        outChannelsArrayName = "NULL"
    idatFile.write("%s, // outChannels (pointer to per-output channel array)\n" % outChannelsArrayName)
    idatFile.write("%s, // numOutputs \n" % ((numOutputs)))
    idatFile.write("AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn \n" % ((strideInElements), (dType)))
    idatFile.write("AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n" % ((strideOutElements), (dType)))
    idatFile.write("%s, // precision \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    isInterleave = int(currPrm.get("isInterleave", 1))
    idatFile.write("%d, // isInputInterleave (1: interleaved, 0: deinterleaved)\n" % isInterleave)
    idatFile.write("},\n")
    idatFile.write("#endif\n")


    if C7100 == "FALSE":
        idatFile.write("#endif // if !defined(__C7100__)\n")

    idatFile.write("\n\n")



def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_split_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate static output pointer arrays and outChannels arrays
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            testId = testCase["ID"]
            numOutputs = int(testCase["numOutputs"])
            outChannelsList = testCase["outChannelsList"]
            demoCase = testCase["demoCase"]

            # Write conditional #ifdef guard matching the test case (same as header includes)
            if demoCase == "true":
                idatFile.write(
                    "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
                    % (int(testId))
                )
            else:
                idatFile.write(
                    "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
                )

            # Output pointers array - references to each output's static data
            out_ptrs = ", ".join([f"(void*)staticRefOut{idx}Case{testId}" for idx in range(numOutputs)])
            idatFile.write(f"__attribute__((unused)) static void *staticOutPtrsCase{testId}[] = {{\n")
            idatFile.write(f"    {out_ptrs}\n")
            idatFile.write("};\n\n")

            # Output channels array - one entry per output (may differ per output)
            channels_list = ", ".join(str(ch) for ch in outChannelsList)
            idatFile.write(f"__attribute__((unused)) static uint32_t outChannelsCase{testId}[] = {{\n")
            idatFile.write(f"    {channels_list}\n")
            idatFile.write("};\n\n")

            idatFile.write("#endif\n\n")

    # generate parameters for test cases
    idatFile.write("static TISP_split_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters and calculate derived values

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    testCase["testId"] = int(testCase["ID"])
    testCase["inSamples"] = int(testCase["samples"])
    testCase["strideIn0"] = int(testCase["strideInElements"])
    testCase["strideOut"] = int(testCase["strideOutElements"])

    # Per-output channel counts. The totalInputChannels column may hold either a
    # bracketed list (e.g. "[8,4,4]") giving each output's channel count, or a scalar
    # (legacy) that is split evenly across the numOutputs column.
    try:
        outChannelsList = ast.literal_eval(testCase["totalInputChannels"])
        if not isinstance(outChannelsList, list):
            raise ValueError("totalInputChannels must be a list")
    except (ValueError, SyntaxError):
        numOutputs = int(testCase["numOutputs"])
        total = int(testCase["totalInputChannels"])
        channelsPerOutput = total // numOutputs
        outChannelsList = [channelsPerOutput] * numOutputs

    testCase["outChannelsList"] = outChannelsList
    testCase["numOutputs"] = len(outChannelsList)
    testCase["totalInputChannels"] = sum(outChannelsList)
    return testCase
   
def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Split Algorithm: Takes 1 input with totalInputChannels and splits into
    N outputs, each with channelsPerOutput channels. All outputs have same
    number of samples.

    Args:
        param1 (:obj: dict): A dict object with all the test case parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    tempbuf=[]
    testId = testCase["ID"]
    dType = testCase["dType"]
    inSamples = testCase["inSamples"]  # Samples (S)
    numOutputs = testCase["numOutputs"]  # Number of outputs (N)
    dataFormat = testCase.get("dataFormat", "INTERLEAVED")  # Default to INTERLEAVED

    # Total input channels to be split
    totalInChannels = testCase["totalInputChannels"]
    outChannelsList = testCase["outChannelsList"]

    # Create an instance of TISP_split
    isInputInterleave = int(testCase.get("isInterleave", 1))
    split_processor = TISP_split(
        dType=dType,
        outChannelsList=outChannelsList,
        numSamples=inSamples,
        isInputInterleave=isInputInterleave
    )

    # [minVal, maxVal] = TISP_utils.minMaxVal(dType)
    [minVal, maxVal] = [-10, 10]

    # Generate aggregated input: (inSamples, totalChannels)
    # Single input buffer with total channels to be split across outputs
    aggregated_size = inSamples * totalInChannels

    if dType[0] == "i" or dType[0] == "u":
        in0_flat = np.random.randint(low=minVal, high=maxVal, size=aggregated_size).astype("int")
        in0 = in0_flat.reshape((1, aggregated_size))
        out = split_processor.exec(in0)
    elif dType[0] == "f":
        in0_flat = np.random.uniform(low=minVal, high=maxVal, size=aggregated_size).astype("float32")
        in0 = in0_flat.reshape((1, aggregated_size))
        out = split_processor.exec(in0)
    elif dType[0] == "d":
        in0_flat = np.random.uniform(low=minVal, high=maxVal, size=aggregated_size).astype("double")
        in0 = in0_flat.reshape((1, aggregated_size))
        out = split_processor.exec(in0)

    headerFileName = "staticRefCase" + str(testId) + ".h"
    # For DEINTERLEAVED: reshape to (totalInChannels, inSamples) before file writing
    # For INTERLEAVED: reshape to (inSamples, totalInChannels)
    if dataFormat == "DEINTERLEAVED":
        in0_for_file = in0_flat.reshape((totalInChannels, inSamples))
    else:  # INTERLEAVED
        in0_for_file = in0_flat.reshape((inSamples, totalInChannels))

    file_io.write_header_file(in0_for_file, out, numOutputs, testCase, headerFileName, dataFormat)
    for i in range(numOutputs):
        tempbuf.append(np.min(out[i]))
        tempbuf.append(np.max(out[i]))
    # return [np.min(out), np.max(out)]
    return tempbuf

