def generate_multisrc_tones(
    num_block: int,
    n_src: int = 3,
    ch_per_src: int = 2,
    samples: int = 12000,
    fs: int = 48000,
    freqs: np.ndarray | None = None,  # shape (n_src, ch_per_src)
    amps: np.ndarray | None = None,  # shape (n_src, ch_per_src)
    phases: np.ndarray | None = None,  # shape (n_src, ch_per_src), radians
    dtype=np.float32,
    is_interleave=0,
) -> np.ndarray:
    """
    Generate multi-source, multi-channel sine data.

    Output shape: (num_block, n_src, ch_per_src, samples)

    Args:
        num_block: Number of time blocks to generate.
        n_src: Number of sources (e.g., 3).
        ch_per_src: Channels per source (e.g., 2).
        samples: Samples per block (e.g., 12000).
        fs: Sample rate in Hz (e.g., 48000 -> 0.25 s for 12000 samples).
        freqs: Frequency matrix in Hz, shape (n_src, ch_per_src).
        amps: Amplitude matrix in [0, 1], shape (n_src, ch_per_src).
        phases: Phase matrix in radians, shape (n_src, ch_per_src).
        dtype: Output dtype.

    Returns:
        np.ndarray with shape (num_block, n_src, ch_per_src, samples)
    """
    # Time vector for a single block
    t = np.arange(samples, dtype=np.float64) / float(fs)  # high precision for phase

    total = n_src * ch_per_src
    freqs = 0 + 500 * np.arange(total, dtype=np.float64)
    freqs = freqs.reshape(n_src, ch_per_src)

    # Default amplitudes (normalized, keep headroom)
    if amps is None:
        # Slightly varying amplitudes per channel
        rng = np.random.default_rng(42)
        amps = rng.uniform(0.3, 0.9, size=(n_src, ch_per_src)).astype(np.float64)
        amps[0, 0] = 0.0  # make the 1st channel as mute

    # Default phases
    if phases is None:
        rng = np.random.default_rng(123)
        phases = rng.uniform(0.0, 2 * np.pi, size=(n_src, ch_per_src)).astype(
            np.float64
        )

    # Validate shapes
    def _check_shape(arr, name):
        if arr.shape != (n_src, ch_per_src):
            raise ValueError(
                f"{name}.shape must be {(n_src, ch_per_src)}, got {arr.shape}"
            )

    _check_shape(freqs, "freqs")
    _check_shape(amps, "amps")
    _check_shape(phases, "phases")

    # Prepare output
    if is_interleave == 1:
        out = np.empty((num_block, n_src, samples, ch_per_src), dtype=dtype)
    else:
        out = np.empty((num_block, n_src, ch_per_src, samples), dtype=dtype)

    for b in range(num_block):
        # angle: (n_src, ch_per_src, samples)
        angle = 2 * np.pi * freqs[..., None] * t[None, None, :] + phases[..., None]
        block = amps[..., None] * np.sin(angle)  # (n_src, ch_per_src, samples)

        if is_interleave == 1:
            # Need (n_src, samples, ch_per_src) → swap last two axes
            # Either of the following is fine:
            # out[b] = np.moveaxis(block, 2, 1)
            out[b] = block.transpose(0, 2, 1)
        else:
            # Already matches (n_src, ch_per_src, samples)
            out[b] = block

    return out


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    inInputs = testCase["inInputs"]
    samplingRate = testCase["samplingRate"]
    currentFadeTime = testCase["currentFadeTime"]
    currentIdx = testCase["currentIdx"]
    numSamples = testCase["numSamples"]
    numChannels = testCase["numChannels"]
    isInteleave = testCase["isInterleave"]
    numBlocks = testCase["numBlocks"]
    dType = testCase["dType"]

    maxSamplesToSmooth = int((samplingRate * currentFadeTime) / 1000)
    if maxSamplesToSmooth > numSamples:
        maxSamplesToSmooth = numSamples

    [minVal, maxVal] = [-1, 1]
    blocks_out = []
    blocks_in = []

    print(
        f"\nTESTID {testId}: nBlocks {numBlocks}, nSamples {numSamples}, nChannels {numChannels}, isInteleave {isInteleave}, dType {dType}"
    )

    # Allocate fader in and fade out gains
    i = np.arange(maxSamplesToSmooth)

    if maxSamplesToSmooth == 1:
        fade_out = np.array([1.0])
        fade_in = np.array([0.0])
    else:
        i = np.arange(maxSamplesToSmooth)
        fade_out = np.cos(i * np.pi / (2 * (maxSamplesToSmooth - 1)))
        fade_in = np.sin(i * np.pi / (2 * (maxSamplesToSmooth - 1)))

    # Use maxSamplesToSmooth for history buffer sizing
    if numSamples < maxSamplesToSmooth:
        history_buffer = np.zeros((numChannels, numSamples))
    else:
        history_buffer = np.zeros((numChannels, maxSamplesToSmooth))

    if testCase["testType"] == "STATIC":
        if isInteleave:
            for i in range(numBlocks):
                if dType == "float" or dType == "double":
                    in0 = np.random.uniform(
                        low=minVal,
                        high=maxVal,
                        size=(inInputs, numSamples, numChannels),
                    )
                    blocks_in.append(in0)
                fade_out_3d = fade_out[:, None]  # shape: (numSamples, 1)
                fade_in_3d = fade_in[:, None]  # shape: (numSamples, 1)
        else:
            for i in range(numBlocks):
                if dType == "float" or dType == "double":
                    in0 = np.random.uniform(
                        low=minVal,
                        high=maxVal,
                        size=(inInputs, numChannels, numSamples),
                    )
                    blocks_in.append(in0)
                fade_out_3d = fade_out[None, :]  # shape becomes ( 1, numSamples)
                fade_in_3d = fade_in[None, :]  # shape becomes ( 1, numSamples)
    else:
        if isInteleave:
            fade_out_3d = fade_out[:, None]  # shape: (numSamples, 1)
            fade_in_3d = fade_in[:, None]  # shape: (numSamples, 1)
        else:
            fade_out_3d = fade_out[None, :]  # shape becomes ( 1, numSamples)
            fade_in_3d = fade_in[None, :]  # shape becomes ( 1, numSamples)

        blocks_in = generate_multisrc_tones(
            num_block=numBlocks,
            n_src=inInputs,
            ch_per_src=numChannels,
            samples=numSamples,
            fs=samplingRate,
            is_interleave=isInteleave,
        )

    if currentIdx >= inInputs or currentIdx < 0:
        currentIdx = 0
    previdx = currentIdx

    blocks_in = np.array(blocks_in)

    changeTime = range(1, numBlocks, numBlocks // 5)
    chnageIdx = [inInputs - 1, (int)((inInputs - 1) / 2), inInputs, -1, 0]

    for i in range(numBlocks):
        if i in changeTime:
            currentIdx = chnageIdx[changeTime.index(i)]
            print(f"Set param at block: {i+1}, newSrc: {currentIdx}")
        else:
            pass

        if currentIdx >= inInputs or currentIdx < 0:
            currentIdx = previdx

        if isInteleave:
            # Block copy
            if previdx == currentIdx or maxSamplesToSmooth == 0:
                block_out = blocks_in[i, currentIdx, :, :]
                blocks_out.append(block_out)
            else:
                # Apply Crossfade
                block_out = fader(
                    in0=blocks_in[i, currentIdx, :maxSamplesToSmooth, :],
                    in1=history_buffer.T[:maxSamplesToSmooth, :],
                    fadeIn=fade_in_3d[:maxSamplesToSmooth, :],
                    fadeOut=fade_out_3d[:maxSamplesToSmooth, :],
                )
                arr_rem = blocks_in[i, currentIdx, maxSamplesToSmooth:, :]
                block_out = np.concatenate([block_out, arr_rem], axis=0)
                blocks_out.append(block_out)
            history_buffer[:, :maxSamplesToSmooth] = blocks_in[
                i, currentIdx, :maxSamplesToSmooth, :
            ].T[:, :maxSamplesToSmooth:]
        else:
            # Block copy
            if previdx == currentIdx or maxSamplesToSmooth == 0:
                block_out = blocks_in[i, currentIdx, :, :]
                blocks_out.append(block_out)
            else:
                # Apply Crossfade
                block_out = fader(
                    in0=blocks_in[i, currentIdx, :, :maxSamplesToSmooth],
                    in1=history_buffer[:, :maxSamplesToSmooth],
                    fadeIn=fade_in_3d[:, :maxSamplesToSmooth],
                    fadeOut=fade_out_3d[:, :maxSamplesToSmooth],
                )
                arr_rem = blocks_in[i, currentIdx, :, maxSamplesToSmooth:]
                block_out = np.concatenate([block_out, arr_rem], axis=1)
                blocks_out.append(block_out)

            history_buffer[:, :maxSamplesToSmooth] = blocks_in[
                i, currentIdx, :, :maxSamplesToSmooth:
            ]

        # Update prev_idx and current_idx
        previdx = currentIdx

    out = np.concatenate(blocks_out, axis=0)

    if isInteleave == 0:
        numBlock, nSrc, ch_per_src, nSamples = blocks_in.shape
        x_src_flat = blocks_in.reshape(numBlock, nSrc * ch_per_src, nSamples)

        # x_out is already (B, ch_per_src, T)
        # Concatenate along the channel axis => (B, nSrc*ch_per_src + ch_per_src, T)
        combined = np.concatenate([x_src_flat, np.array(blocks_out)], axis=1)

        # Reorder to frames for soundfile: (B, T, C) -> (B*T, C)
        frames = np.moveaxis(combined, 2, 1).reshape(
            numBlock * nSamples, nSrc * ch_per_src + ch_per_src
        )

        # Optional: ensure float32 (soundfile will quantize if subtype is PCM_16/24/32)
        frames = frames.astype(np.float32, copy=False)

        # Write WAV (interleaved)
        if HAS_SOUNDFILE:
            sf.write(
                "./Outputs/staticRefCase" + str(testId) + ".wav", frames, samplingRate
            )  # default subtype based on dtype

    else:
        numBlock, nSrc, nSamples, ch_per_src = blocks_in.shape

        # Move time axis to middle → (B, T, nSrc, ch)
        x_in = np.moveaxis(blocks_in, 2, 1)

        # Flatten nSrc × ch → total input channels → (B, T, nSrc*ch)
        x_in_flat = x_in.reshape(numBlock, nSamples, nSrc * ch_per_src)

        # Output is already (B, T, ch)
        x_out = np.asarray(blocks_out)  # ensure ndarray

        # Concatenate input + output along channel axis → (B, T, nSrc*ch + ch)
        combined = np.concatenate([x_in_flat, x_out], axis=2)

        # Flatten batches: (B, T, C) → (B*T, C)
        frames = combined.reshape(numBlock * nSamples, nSrc * ch_per_src + ch_per_src)

        # Convert to float32 for wav
        frames = frames.astype(np.float32, copy=False)

        # Write WAV (interleaved)
        if HAS_SOUNDFILE:
            sf.write(
                "./Outputs/staticRefCase" + str(testId) + ".wav", frames, samplingRate
            )  # default subtype based on dtype

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(
        blocks=blocks_in,
        in1=fade_in,
        in2=fade_out,
        out=out,
        smoothSamples=maxSamplesToSmooth,
        testCase=testCase,
        headerFileName=headerFileName,
    )

    min_output = np.min(out)
    max_output = np.max(out)
    return [min_output, max_output]


