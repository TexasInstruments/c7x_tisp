def plot_mixer_signals(in_signal, out_signal, testCase, plot_coeffs=False):
    """Plot mixer input/output signals. Expects PLANAR format (Channels, Samples)."""

    testId = testCase["ID"]
    numBlocks = int(testCase["numBlocks"])
    totalInputChannels = int(testCase["totalInputChannels"])
    numOutputChannels = int(testCase["numOutputChannels"])

    # Adjusted to account for numBlocks to prevent plotting mismatch
    inSamples = int(testCase["inSamples"])
    testType = testCase.get("testType", "STATIC")

    outputDir = "../../../AUDIOLIB/TISP_mixer/plots/"
    if not os.path.exists(outputDir):
        os.makedirs(outputDir)

    # Input format is PLANAR: (Channels, Samples)
    # Transpose to (Samples, Channels) for plotting
    in_signal = np.array(in_signal).T  # Now (Samples, Channels)
    out_signal = np.array(out_signal).T  # Now (Samples, Channels)

    max_channels_to_plot = min(4, totalInputChannels, numOutputChannels)

    fig, axes = plt.subplots(2, 1, figsize=(14, 8))
    time_axis = np.arange(inSamples)

    # Plot INPUT
    for ch in range(min(max_channels_to_plot, totalInputChannels)):
        axes[0].plot(time_axis, in_signal[:, ch], label=f"InCh {ch}")

    axes[0].set_title(f"Test {testId} - Mixer Input (Merged) ({testType})")
    axes[0].legend()
    axes[0].grid(True, alpha=0.3)

    # Plot OUTPUT
    for ch in range(min(max_channels_to_plot, numOutputChannels)):
        axes[1].plot(time_axis, out_signal[:, ch], label=f"OutCh {ch}")

    axes[1].set_title(f"Test {testId} - Mixer Output ({testType})")
    axes[1].legend()
    axes[1].grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(f"{outputDir}/test_{testId}_mixer_signals.png", dpi=150)
    plt.close(fig)

    if plot_coeffs and "coefficients" in testCase:
        coeffs = np.array(testCase["coefficients"]).reshape(
            numOutputChannels, totalInputChannels
        )
        fig, ax = plt.subplots(figsize=(max(10, totalInputChannels * 0.5), 6))
        im = ax.imshow(coeffs, cmap="RdBu", aspect="auto", interpolation="nearest")
        ax.set_title(f"Test {testId} - Mixer Coefficient Matrix")
        plt.colorbar(im, ax=ax)
        plt.savefig(f"{outputDir}/test_{testId}_mixer_coeffs.png", dpi=150)
        plt.close(fig)
