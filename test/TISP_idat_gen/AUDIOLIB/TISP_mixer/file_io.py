from __future__ import print_function
from subprocess import call
from sys import platform

import os
import numpy as np
import matplotlib.pyplot as plt
import ast
from scipy.io import wavfile


def write_attributes(f, attributes, stringToWrite):
    """Write data arrays with platform-specific attributes."""
    f.write("#ifdef WIN32\n")
    f.write(stringToWrite)
    f.write("#else\n")
    f.write(attributes + stringToWrite)
    f.write("#endif\n")
    f.write("{\n")


def write_header_file(
    individual_inputs,
    final_output,
    coefficients,
    testCase,
    headerFileName,
    inChannelsArray=None,
):
    """
    Generates a C header file containing:
    1. Individual Input Arrays (Source)
    2. Final Output Array (Mixer Output)
    3. Coefficients
    4. Channel Counts
    """
    testId = testCase["ID"]
    dType = testCase["dType"]
    numBlocks = testCase["numBlocks"]

    outputDir = "../../../AUDIOLIB/TISP_mixer/test_data/"
    if not os.path.exists(outputDir):
        os.makedirs(outputDir)

    filepath = os.path.join(outputDir, headerFileName)

    attributesStatic = '__attribute__((section(".staticData"))) static '

    with open(filepath, "w") as f:
        f.write(f"/* Autogenerated test data for Test Case ID: {testId} */\n")
        f.write(
            "/* Contains: Individual Inputs -> Merged Input -> Coefficients -> Final Output */\n\n"
        )

        # 1. Write Individual Inputs
        f.write("/* ---------------- Individual Source Inputs ---------------- */\n")
        for i, input_array in enumerate(individual_inputs):
            array_size = input_array.size
            array_name = f"staticRefInput{i}Case{testId}"

            # Ensure 2D for consistent writing loop
            if input_array.ndim == 1:
                input_array = np.atleast_2d(input_array)

            decl = f"{dType} {array_name}[{array_size}] =\n"
            write_attributes(f, attributesStatic, decl)

            rows, cols = input_array.shape
            for r in range(rows):
                f.write("    ")
                for c in range(cols):
                    val = input_array[r, c]
                    if "float" in dType or "double" in dType:
                        f.write(f"{val:.8f}, ")
                    else:
                        f.write(f"{val}, ")
                f.write("\n")
            f.write("};\n\n")

        # 2. Write Coefficients
        f.write("/* ---------------- Mixer Coefficients ---------------- */\n")
        coeff_size = coefficients.size
        coeff_name = f"staticRefCoeffCase{testId}"

        decl = f"{dType} {coeff_name}[{coeff_size}] =\n"
        write_attributes(f, attributesStatic, decl)

        flat_coeffs = coefficients.flatten()
        for i, val in enumerate(flat_coeffs):
            f.write(f"{val:.8f}, ")
            if (i + 1) % 8 == 0:
                f.write("\n")
        f.write("\n};\n\n")

        # 3. Write Final Output
        f.write("/* ---------------- Final Mixer Output ---------------- */\n")
        out_size = final_output.size
        out_name = f"staticRefOutCase{testId}"

        decl = f"{dType} {out_name}[{out_size}] =\n"
        write_attributes(f, attributesStatic, decl)

        if final_output.ndim == 1:
            final_output = np.atleast_2d(final_output)

        rows, cols = final_output.shape
        for r in range(rows):
            f.write("    ")
            for c in range(cols):
                val = final_output[r, c]
                f.write(f"{val:.8f}, ")
            f.write("\n")
        f.write("};\n\n")

        # 4. Write Channel Counts
        if inChannelsArray:
            arr_vals = ast.literal_eval(f"[{inChannelsArray}]")
            size = len(arr_vals)
            name = f"inChannelsCase{testId}"
            decl = f"int32_t {name}[{size}] =\n"
            write_attributes(f, attributesStatic, decl)
            f.write(f"    {inChannelsArray}\n")
            f.write("};\n\n")

    if platform.startswith("linux"):
        try:
            call(["indent", "-nut", "-i3", "-l100", filepath])
            call(["rm", filepath + "~"])
        except Exception:
            pass


