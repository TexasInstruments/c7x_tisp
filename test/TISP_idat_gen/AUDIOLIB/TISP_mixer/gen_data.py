def gen_testCaseParams(idatFile, currPrm):
    """Generate and write test case parameters to idat file."""
    testId = currPrm["ID"]
    dType = currPrm["dType"]
    inSamples = currPrm["inSamples"]
    numBlocks = currPrm["numBlocks"]

    # Aggregator specific params
    inChannelsList = ast.literal_eval(currPrm["inChannels"])
    numInputs = len(inChannelsList)
    totalInputChannels = sum(inChannelsList)

    isInputInterleave = currPrm["isInputInterleave"]

    # Mixer specific params
    numOutputChannels = currPrm["numOutputChannels"]

    strideIn = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]

    AUDIOLIB_dType = TISP_utils.resolve_AUDIOLIB_dType(dType)

    # Define pointers
    if testType in ["STATIC", "SINE"]:
        testTypeOut = "STATIC"
        # The array of pointers to individual inputs (Aggregator)
        pInputs = f"staticRefInCase{testId}"
        # The final output of the mixer
        finalOut = f"staticRefOutCase{testId}"
        # Mixer Coefficients
        coefficients = f"staticRefCoeffCase{testId}"
        # Channel counts array
        inChannelsArrayName = f"inChannelsCase{testId}"
    else:
        testTypeOut = testType
        pInputs = "NULL"
        finalOut = "NULL"
        coefficients = "NULL"
        inChannelsArrayName = "NULL"

    idatFile.write("#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % int(testId))
    idatFile.write("{\n")
    idatFile.write("%s, // Test Pattern\n" % testTypeOut)

    # Pointers
    idatFile.write(
        f"    (void**){pInputs}, // pInputs (Array of pointers to individual source inputs)\n"
    )
    idatFile.write("%s, // Final Output Signal (Output of Mixer)\n" % finalOut)
    idatFile.write("%s, // Mixer Coefficients\n" % coefficients)
    idatFile.write(
        "%s, // inChannels List (Array of channel counts)\n" % inChannelsArrayName
    )

    # Parameters
    idatFile.write("%s, // Sample Data Type\n" % AUDIOLIB_dType)
    idatFile.write("%d, // inSamples (Samples per channel)\n" % int(inSamples))
    idatFile.write("%d, // Total Input Channels\n" % int(totalInputChannels))
    idatFile.write("%d, // Number of Individual Inputs (Groups)\n" % int(numInputs))
    idatFile.write("%d, // Number of Output Channels\n" % int(numOutputChannels))

    # Interleave Flag
    idatFile.write("%d, // isInputInterleave\n" % int(isInputInterleave))

    # Strides
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn \n"
        % (strideIn, dType)
    )
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
        % (strideOut, dType)
    )

    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d,// numBlocks \n" % ((numBlocks)))
    idatFile.write("%d, // Test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file."""
    header_path = os.path.join("..", "..", "common", "ti_lice_header_idat.txt")
    if os.path.exists(header_path):
        with open(header_path, "r") as fIn:
            lines = fIn.readlines()
        idatFile.writelines(lines)
    else:
        idatFile.write(
            "/* autogenerated idat header - original header file missing */\n"
        )

    includeString = '#include "TISP_mixer_idat.h"\n'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")

    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)
    # Generate extern/ifdefs for arrays
    for testCase in testCases:
        if testCase["testType"] in ["STATIC", "SINE"]:
            testId = testCase["ID"]
            idatFile.write(
                f"#if (defined(ALL_TEST_CASES) || (TEST_CASE == {testId}))\n"
            )
            idatFile.write(f"extern {testCase['dType']} staticRefOutCase{testId}[];\n")
            idatFile.write(
                f"extern {testCase['dType']} staticRefCoeffCase{testId}[];\n"
            )
            idatFile.write(f"extern int32_t inChannelsCase{testId}[];\n")

            # Generate the array of pointers for inputs
            inChannelsList = ast.literal_eval(testCase["inChannels"])
            numInputs = len(inChannelsList)
            for i in range(numInputs):
                idatFile.write(
                    f"extern {testCase['dType']} staticRefInput{i}Case{testId}[];\n"
                )

            idatFile.write(f"static void *staticRefInCase{testId}[{numInputs}] = {{\n")
            for i in range(numInputs):
                idatFile.write(f"    (void *)staticRefInput{i}Case{testId},\n")
            idatFile.write("};\n")
            idatFile.write("#endif\n\n")

    idatFile.write("static TISP_mixer_testParams_t testParams[] =  ")
    idatFile.write("{\n")
    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)
    idatFile.write("};\n\n")

    func_path = "test_param_function.txt"
    if os.path.exists(func_path):
        with open(func_path, "r") as fIn:
            lines = fIn.readlines()
        idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert string parameters to appropriate types."""
    testCase["ID"] = testCase.get("ID", testCase.get("testId", "0"))
    testCase["testId"] = int(testCase["ID"])
    testCase["inSamples"] = int(testCase.get("inSamples", 64))

    # Aggregator Parsing
    try:
        inChannelsList = ast.literal_eval(testCase["inChannels"])
        if not isinstance(inChannelsList, list):
            raise ValueError("inChannels must be a list")
        testCase["totalInputChannels"] = sum(inChannelsList)
        testCase["inChannelsList"] = inChannelsList
    except (ValueError, SyntaxError):
        raise ValueError(f"Invalid inChannels format for test case ID {testCase['ID']}")

    testCase["numOutputChannels"] = int(testCase.get("numOutputChannels", 1))
    testCase["samplingRate"] = int(testCase.get("samplingRate", 48000))
    testCase["isInputInterleave"] = int(testCase.get("isInputInterleave", 0))

    # Calculate strides
    if "strideInElements" in testCase:
        testCase["strideInElements"] = int(testCase["strideInElements"])
    else:
        testCase["strideInElements"] = int(
            testCase["inSamples"] * testCase["totalInputChannels"]
        )

    if "strideOutElements" in testCase:
        testCase["strideOutElements"] = int(testCase["strideOutElements"])
    else:
        testCase["strideOutElements"] = int(
            testCase["inSamples"] * testCase["numOutputChannels"]
        )

    testCase["plotSignals"] = (
        str(testCase.get("plotSignals", "FALSE")).upper() == "TRUE"
    )
    testCase["waveFiles"] = str(testCase.get("waveFiles", "FALSE")).upper() == "TRUE"
    testCase["amplitude"] = float(testCase.get("amplitude", 1.0))
    testCase["frequency"] = float(testCase.get("frequency", 2000.0))
    testCase["dType"] = str(testCase.get("dType", "float")).lower()

    if testCase["dType"] not in ("float", "double"):
        testCase["dType"] = "float"

    testCase["dtype_np"] = DTYPE_MAP[testCase["dType"]]
    testCase["outputDataLocation"] = testCase.get("outputDataLocation", "INTERNAL")
    testCase["testType"] = str(testCase.get("testType", "STATIC")).upper()
    testCase["numReps"] = int(testCase.get("numReps", 1))
    testCase["numBlocks"] = int(testCase.get("numBlocks", 1))

    return testCase


def gen_test_case_header_file(testCase):
    testId = testCase["testId"]
    inSamples = testCase["inSamples"]
    totalInputChannels = testCase["totalInputChannels"]
    numOutputChannels = testCase["numOutputChannels"]
    inChannelsList = testCase["inChannelsList"]
    numBlocks = testCase["numBlocks"]

    isInputInterleave = testCase["isInputInterleave"]

    dtype_np = testCase["dtype_np"]
    minVal, maxVal = -testCase["amplitude"], testCase["amplitude"]

    # 4. GENERATE COEFFICIENTS
    # Coefficients do NOT scale with numBlocks; they are static properties of the mixer
    coefficients = generate_random_coeffs(
        totalInputChannels, numOutputChannels, seed=testId
    )
    coefficients = coefficients.astype(dtype_np)
    testCase["coefficients"] = coefficients

    # 1. GENERATE INDIVIDUAL INPUTS (Aggregator Step)
    blocks_out = []
    blocks_in = []

    # Calculate total samples considering numBlocks
    total_samples = inSamples
    # For aggregation logic, we need to create inputs based on interleave flag
    for i in range(numBlocks):
        merged_planar = []
        individual_inputs = []
        planar_inputs_for_agg = []
        for num_ch in inChannelsList:
            if isInputInterleave:
                # Shape: (TotalSamples, Channels)
                shape = (total_samples, num_ch)
            else:
                # Shape: (Channels, TotalSamples)
                shape = (num_ch, total_samples)

            if testCase["testType"] == "STATIC":
                inp = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(
                    dtype_np
                )
            else:
                inp = np.zeros(shape, dtype=dtype_np)

            individual_inputs.append(inp)
            blocks_in.append(inp)
            # 2. MERGE INPUTS (Aggregator Step -> Mixer Input)
            # The aggregator merges the individual inputs.

        if isInputInterleave:
            # If inputs are interleaved (TotalSamples, Ch), transpose to planar (Ch, TotalSamples) for stacking
            for inp in individual_inputs:
                planar_inputs_for_agg.append(inp.T)
        else:
            planar_inputs_for_agg = individual_inputs
        # Stack vertically to get (TotalChannels, TotalSamples) - PLANAR format
        merged_planar = np.vstack(planar_inputs_for_agg)

        # Merged input buffer is in planar format (TotalChannels, TotalSamples)
        # This is passed directly to the mixer - NO TRANSPOSE

        # 5. RUN MIXER
        # Input: (TotalChannels, TotalSamples) - planar
        # Output: (OutputChannels, TotalSamples) - planar

        output = mixer_process(
            merged_planar, coefficients, totalInputChannels, numOutputChannels
        )
        blocks_out.append(output)
    if isInputInterleave:
        mixer_block_input = np.hstack(blocks_in)
        mixer_block_input = mixer_block_input.T

        mixer_output = np.hstack(blocks_out)
        mixer_outputT = mixer_output.T
    else:
        mixer_block_input = np.vstack(blocks_in)
        mixer_output = np.vstack(blocks_out)
        mixer_outputT = mixer_output

    # 6. WRITE HEADER FILE
    headerFileName = f"staticRefCase{testId}.h"
    inChannelsArrayStr = ", ".join(str(ch) for ch in inChannelsList)

    file_io.write_header_file(
        blocks_in,
        mixer_outputT,
        coefficients,
        testCase,
        headerFileName,
        inChannelsArrayStr,
    )

    return [np.min(mixer_output), np.max(mixer_output)]


# --- MAIN EXECUTION ---

testCasesCsvFile = "test_cases_list.csv"
testIdList = list(range(0, 100))
myArgs = TISP_utils.getCmdLineArgs()

if not os.path.exists(testCasesCsvFile):
    raise FileNotFoundError(f"Test cases CSV not found: {testCasesCsvFile}")

with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)

    # Preprocess
    for i, testCase in enumerate(testCases):
        testCases[i] = process_test_case(testCase)

    # Generate Data
    for testCase in testCases:
        if myArgs.allCases or int(testCase["ID"]) in testIdList:
            if testCase["testType"] == "STATIC":
                [minY, maxY] = gen_test_case_header_file(testCase)
                print(
                    f"Test case {testCase['ID']} generated. Min: {minY:.4f}, Max: {maxY:.4f}"
                )
            else:
                print(f"Skipping test {testCase['ID']} (Type: {testCase['testType']})")

# Generate IDAT
idatFileName = "../../../AUDIOLIB/TISP_mixer/TISP_mixer_idat.c"
with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)

if platform == "linux" or platform == "linux2":
    try:
        call(["clang-format", "-style=file", "-i", idatFileName])
        call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
        call(["rm", idatFileName + "~"])
    except Exception:
        pass

print("\nIdat file generation completed")
