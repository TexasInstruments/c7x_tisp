def write_attributes(f, attributes, stringToWrite):
    """Write data arrays with platform-specific attributes."""
    f.write("#ifdef WIN32\n")
    f.write(stringToWrite)
    f.write("#else\n")
    f.write(attributes + stringToWrite)
    f.write("#endif\n")
    f.write("{\n")


def write_header_file(individual_inputs, merged_output, testCase, headerFileName, inChannelsArray=None):
    """
    Generates a C header file containing:
    1. Individual Input Arrays (Source)
    2. Merged Output Array (Concatenated)
    """
    testId = testCase["ID"]
    dType = testCase["dType"]

    outputDir = "../../../AUDIOLIB/TISP_concat/test_data/"
    if not os.path.exists(outputDir):
        os.makedirs(outputDir)

    filepath = os.path.join(outputDir, headerFileName)

    attributesStatic = '__attribute__((section(".staticData"))) static '

    with open(filepath, "w") as f:
        f.write(f"/* Autogenerated test data for Test Case ID: {testId} */\n")
        f.write("/* Contains: Individual Inputs -> Merged Output */\n\n")

        # 1. Write Individual Inputs
        f.write("/* ---------------- Individual Source Inputs ---------------- */\n")
        for i, input_array in enumerate(individual_inputs):
            array_size = input_array.size
            array_name = f"staticRefInput{i}Case{testId}"

            # Ensure 2D for consistent writing loop
            if input_array.ndim == 1:
                input_array = np.atleast_2d(input_array)

            decl = f"{dType} {array_name}[{array_size}] =\n"
            write_attributes(f, attributesStatic, decl)

            rows, cols = input_array.shape
            for r in range(rows):
                f.write("    ")
                for c in range(cols):
                    val = input_array[r, c]
                    if "float" in dType or "double" in dType:
                        f.write(f"{val:.8f}f, ")
                    else:
                        f.write(f"{val}, ")
                f.write("\n")
            
            f.write("};\n\n")

        # 2. Write Merged Output
        f.write("/* ---------------- Concatenated Output ---------------- */\n")
        out_size = merged_output.size
        out_name = f"staticRefOutCase{testId}"

        decl = f"{dType} {out_name}[{out_size}] =\n"
        write_attributes(f, attributesStatic, decl)

        if merged_output.ndim == 1:
            merged_output = np.atleast_2d(merged_output)

        rows, cols = merged_output.shape
        for r in range(rows):
            f.write("    ")
            for c in range(cols):
                val = merged_output[r, c]
                if "float" in dType or "double" in dType:
                    f.write(f"{val:.8f}f, ")
                else:
                    f.write(f"{val}, ")
            f.write("\n")
        f.write("\n};")
        f.write("\n\n")
        f.close()

    if platform.startswith("linux"):
        try:
            call(["indent", "-nut", "-i3", "-l100", filepath])
            call(["rm", filepath + "~"])
        except Exception:
            pass
