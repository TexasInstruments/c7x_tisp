def get_soc_guard(am275_soc_value):
    """Generate SOC preprocessor guard based on 'AM275 SOC' column value"""
    if am275_soc_value.lower() == "yes":
        return None
    else:
        return "!(SOC == AM275 && !defined(HOST_EMULATION))"


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    testId = currPrm["ID"]
    dType = currPrm["dType"]
    mode = currPrm["mode"]
    maxDelay = currPrm["maxDelay"]
    interleave = currPrm["interleave"]
    numChannels = currPrm["numChannels"]
    numSamples = currPrm["numSamples"]
    strideIn = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    C7100 = currPrm["C7100"]
    numBlocks = currPrm["numBlocks"]
    am275_soc = currPrm.get("AM275 SOC", "yes")

    if testType == "STATIC":
        inputBuff = "staticRefInCase" + testId
        delaySizeBuff = "staticDelaySizeCase" + testId
        outputBuff = "staticRefOutCase" + testId
        delayBuff = "staticUpdatedDelayCase" + testId
    else:
        inputBuff = "NULL"
        delaySizeBuff = "NULL"
        outputBuff = "NULL"
        delayBuff = "NULL"
    if C7100 == "FALSE":
        testParamsFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    soc_guard = get_soc_guard(am275_soc)
    if soc_guard:
        idatFile.write("#if %s\n" % soc_guard)

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // maxDelay \n" % ((maxDelay)))
    idatFile.write("%s, // precision \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // mode \n" % ((mode)))
    idatFile.write("%s, // Input buffer\n" % ((inputBuff)))
    idatFile.write("%s, // DelaySize buffer \n" % ((delaySizeBuff)))
    idatFile.write("%s, // Output buffer \n" % ((outputBuff)))
    idatFile.write("%s, // updatedDelay buffer \n" % ((delayBuff)))
    idatFile.write("%s, // Interleave \n" % ((interleave)))
    idatFile.write("%s, // numChannels \n" % ((numChannels)))
    idatFile.write("%s, // numSamples \n" % ((numSamples)))
    idatFile.write(
        "%s * sizeof(%s), // stride of input buffer \n" % ((strideIn), (dType))
    )
    idatFile.write(
        "%s * sizeof(%s), // stride of output buffer \n" % ((strideOut), (dType))
    )
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d,// numBlocks \n" % ((numBlocks)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    if soc_guard:
        idatFile.write("#endif  // SOC guard\n")
    idatFile.write("#endif  // TEST_CASE guard\n")

    if C7100 == "FALSE":
        testParamsFile.write("#endif // if !defined(__C7100__)\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_delayNChannel_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_delayNChannel_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """
    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["mode"] = int(testCase["mode"])
    testCase["interleave"] = int(testCase["interleave"])
    testCase["numChannels"] = int(testCase["numChannels"])
    testCase["numSamples"] = int(testCase["numSamples"])
    testCase["strideIn"] = int(testCase["strideInElements"])
    testCase["strideOut"] = int(testCase["strideOutElements"])
    testCase["maxDelay"] = int(testCase["maxDelay"])
    testCase["numBlocks"] = int(testCase["numBlocks"])
    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    mode = testCase["mode"]
    testId = testCase["ID"]
    dType = testCase["dType"]
    interleave = testCase["interleave"]
    numChannels = testCase["numChannels"]
    numSamples = testCase["numSamples"]
    maxDelay = testCase["maxDelay"]
    numBlocks = testCase["numBlocks"]

    if dType == "int8_t" or dType == "uint8_t":
        bits = 8
    elif dType == "int16_t" or dType == "uint16_t":
        bits = 16
    elif dType == "int32_t" or dType == "uint32_t":
        bits = 32
    else:
        bits = 32

    # unsigned integer
    if dType[0] == "u":
        minVal = 0
        maxVal = (2**bits) - 1
    else:
        minVal = -(2 ** (bits - 1))
        maxVal = 2 ** (bits - 1)

    minDelaySize = 1
    maxDelaySize = maxDelay

    if interleave == 1:
        if dType == "float":
            inputBuff = np.random.uniform(
                low=minVal, high=maxVal, size=(numBlocks * numSamples, numChannels)
            ).astype("float32")

        elif dType == "double":
            inputBuff = np.random.uniform(
                low=minVal, high=maxVal, size=(numBlocks * numSamples, numChannels)
            ).astype("double")

        else:
            raise ValueError(f"Unsupported data type: {dType}")

    else:
        if dType == "float":
            inputBuff = np.random.randint(
                low=minVal, high=maxVal, size=(numChannels, numBlocks * numSamples)
            ).astype("float32")

        elif dType == "double":
            inputBuff = np.random.randint(
                low=minVal, high=maxVal, size=(numChannels, numBlocks * numSamples)
            ).astype("double")

        else:
            raise ValueError(f"Unsupported data type: {dType}")

    delaySize = np.random.randint(
        low=minDelaySize, high=maxDelaySize, size=(numChannels)
    ).astype("uint32")
    if maxDelay not in delaySize:
        delaySize[numChannels - 1] = maxDelay
    np.random.shuffle(delaySize)

    if mode == 0:
        delayBuffSize = numSamples + maxDelay
        delayBuff = np.zeros((numChannels, delayBuffSize), dtype=dType)
    elif mode == 1:
        if (numSamples + maxDelay) < 512:
            delayBuffSize = 512
        else:
            delayBuffSize = 2 ** int(np.ceil(np.log2(numSamples + maxDelay)))
        delayBuff = np.zeros((numChannels, delayBuffSize), dtype=dType)

    outBuff = np.zeros((numChannels, numBlocks * numSamples), dtype=inputBuff.dtype)

    inputBuffTemp = inputBuff

    if interleave == 1:
        inputBuff = inputBuff.T

    if mode == 0:
        for numExecRep in range(numBlocks):
            for ch in range(numChannels):
                if delaySize[ch] < numSamples:
                    for i in range(delaySize[ch]):
                        outBuff[ch, numExecRep * numSamples + i] = delayBuff[ch, i]
                    for i in range(numSamples - delaySize[ch]):
                        outBuff[ch, numExecRep * numSamples + delaySize[ch] + i] = (
                            inputBuff[ch, numExecRep * numSamples + i]
                        )
                    if delaySize[ch] > 0:
                        for i in range(delaySize[ch]):
                            delayBuff[ch, i] = inputBuff[
                                ch,
                                numExecRep * numSamples
                                + (numSamples - delaySize[ch])
                                + i,
                            ]
                else:
                    for i in range(numSamples):
                        outBuff[ch, numExecRep * numSamples + i] = delayBuff[ch, i]
                    for i in range(delaySize[ch] - numSamples):
                        delayBuff[ch, i] = delayBuff[ch, numSamples + i]
                    for i in range(numSamples):
                        delayBuff[ch, (delaySize[ch] - numSamples) + i] = inputBuff[
                            ch, numExecRep * numSamples + i
                        ]
    elif mode == 1:
        readIdx = [0] * numChannels
        writeIdx = [0] * numChannels
        for ch in range(numChannels):
            writeIdx[ch] = delaySize[ch]

        for numExecRep in range(numBlocks):
            for ch in range(numChannels):
                # Write Delay Buffer
                writeSampleCnt1 = min((delayBuffSize - writeIdx[ch]), numSamples)
                writeSampleCnt2 = numSamples - writeSampleCnt1
                for i in range(writeSampleCnt1):
                    delayBuff[ch, writeIdx[ch] + i] = inputBuff[
                        ch, numExecRep * numSamples + i
                    ]
                if (writeIdx[ch] + numSamples) >= delayBuffSize:
                    writeIdx[ch] = 0
                else:
                    writeIdx[ch] = writeIdx[ch] + numSamples
                if writeSampleCnt2 > 0:
                    for i in range(writeSampleCnt2):
                        delayBuff[ch, i] = inputBuff[
                            ch,
                            (numExecRep * numSamples)
                            + (writeSampleCnt1 - writeIdx[ch])
                            + i,
                        ]
                    writeIdx[ch] = writeSampleCnt2

                # Read Delay Buffer
                readSampleCnt1 = min((delayBuffSize - readIdx[ch]), numSamples)
                readSampleCnt2 = numSamples - readSampleCnt1
                for i in range(readSampleCnt1):
                    outBuff[ch, numExecRep * numSamples + i] = delayBuff[
                        ch, readIdx[ch] + i
                    ]
                if (readIdx[ch] + numSamples) >= delayBuffSize:
                    readIdx[ch] = 0
                else:
                    readIdx[ch] = readIdx[ch] + numSamples

                if readSampleCnt2 > 0:
                    for i in range(readSampleCnt2):
                        outBuff[
                            ch,
                            (numExecRep * numSamples)
                            + (readSampleCnt1 - readIdx[ch])
                            + i,
                        ] = delayBuff[ch, i]
                    readIdx[ch] = readSampleCnt2

    if interleave == 1:
        outBuff = outBuff.T

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(
        inputBuffTemp,
        delaySize,
        outBuff,
        delayBuff,
        testCase,
        headerFileName,
        delayBuffSize,
    )
    return [np.min(outBuff), np.max(outBuff)]


