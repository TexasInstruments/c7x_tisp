from __future__ import print_function
from subprocess import call
from sys import platform
import os


def write_header_file(
    input_signal,
    output_signal,
    test_case,
    header_file_name,
    output_block_size,
    output_num_channels,
):
    """Write input and output signals to a C header file for subBlockStatistics kernel test case verification.

    Args:
        input_signal (list): Planar input signal samples [ch0_samples, ch1_samples, ...], length inputBlockSize * numChannels.
        output_signal (list): Output signal samples, if flagPerChanStats=TRUE, length outputBlockSize * outputNumChannels.
        test_case (dict): Test case parameters (testId, inputBlockSize, subBlockSize, numChannels, statisticsType, testType, flagPerChanStats, sampleDataType).
        header_file_name (str): Name of the header file to write (e.g., 'staticRefCase1.h').
        output_block_size (int): Number of output samples per channel.
        output_num_channels (int): Number of output channels (numChannels if flagPerChanStats=TRUE, else 1).
    """
    test_id = test_case["testId"]
    input_block_size = test_case["inputBlockSize"]
    subblock_size = test_case["subBlockSize"]
    num_channels = test_case["numChannels"]
    statistics_type = test_case["statisticsType"]
    flag_per_chan_stats = test_case["flagPerChanStats"]
    data_type = test_case["sampleDataType"]
    numBlocks = test_case["numBlocks"]

    # Determine C data type
    c_data_type = "double" if data_type == "double" else "float"
    # Use higher precision for double to avoid truncation
    format_spec = "%.17g" if data_type == "double" else "%.9f"

    # Calculate total input samples
    total_input_samples = input_block_size * num_channels * numBlocks

    # Map statisticsType to descriptive name
    stat_names = {
        0: "maximum",
        1: "minimum",
        2: "maximum absolute value",
        3: "mean",
        4: "RMS",
        5: "standard deviation",
        6: "variance",
        7: "average energy",
        8: "sum",
        9: "sum of squares",
    }
    stat_name = stat_names.get(statistics_type, "unknown")

    output_dir = "../../../AUDIOLIB/TISP_subBlockStatistics/test_data/"
    os.makedirs(output_dir, exist_ok=True)

    with open(os.path.join(output_dir, header_file_name), "w") as f:
        # Write description
        f.write(f"/** \n")
        f.write(f" * @file {header_file_name}\n")
        f.write(
            f" * @brief Test case {test_id} reference data for AUDIOLIB_subBlockStatistics kernel.\n"
        )
        f.write(f" *\n")
        f.write(
            f" * Input: {num_channels} channels, {input_block_size} samples per channel, {numBlocks } numBlocks planar format ([ch0, ch1, ...]).\n"
        )
        f.write(f" * Subblock size: {subblock_size} samples per channel.\n")
        f.write(f" * Total input samples: {total_input_samples}.\n")
        f.write(
            f" * Output: {output_num_channels} channels, {output_block_size} samples per channel.\n"
        )
        f.write(f" * Statistic: {stat_name} (statisticsType={statistics_type}).\n")
        f.write(f" * Data type: {c_data_type} (sampleDataType={data_type}).\n")
        f.write(
            f" * Generated by gen_data.py for testType=STATIC, flagPerChanStats={'TRUE' if flag_per_chan_stats else 'FALSE'}.\n"
        )
        f.write(f" */\n\n")

        # Write input signal with channel and subblock comments
        f.write(
            f"// Input samples in planar format: [{num_channels} channels, {input_block_size} samples per channel, {numBlocks} numBlocks]\n"
        )
        f.write(f"#ifdef WIN32\n")
        f.write(f"{c_data_type} staticRefInCase{test_id}[{total_input_samples}] =\n")
        f.write(f"#else\n")
        f.write(
            f'__attribute__((section(".staticData"))) static {c_data_type} staticRefInCase{test_id}[{total_input_samples}] =\n'
        )
        f.write(f"#endif\n")
        f.write("{\n")
        blk = 0
        chNum = 0
        for ch in range(num_channels * numBlocks):
            start_idx = ch * input_block_size
            end_idx = start_idx + input_block_size
            f.write(f"// Block {blk}\n")
            f.write(f"// Channel {chNum}: samples [{start_idx}:{end_idx - 1}]\n")
            for i in range(input_block_size):
                global_idx = ch * input_block_size + i
                # Check for start of a subblock
                if i % subblock_size == 0:
                    subblock_idx = i // subblock_size
                    subblock_start = start_idx + i
                    subblock_end = subblock_start + subblock_size - 1
                    f.write(
                        f"// Subblock {subblock_idx} for Channel {chNum}: samples [{subblock_start}:{subblock_end}]\n"
                    )
                f.write(f"    {format_spec % input_signal[global_idx]}")
                f.write("," if global_idx < len(input_signal) - 1 else "")
                # Check for end of a subblock
                if (i + 1) % subblock_size == 0:
                    f.write(
                        f"\n// End of Subblock {subblock_idx} for Channel {chNum}\n"
                    )
                else:
                    f.write("\n" if (i + 1) % 8 == 0 else "")
            if chNum < num_channels * numBlocks - 1:
                f.write(f"// End of Channel {chNum}\n\n")
                chNum = chNum + 1
                if chNum > num_channels - 1:
                    blk = blk + 1
                    chNum = 0
        f.write("};\n\n")

        # Write output signal with statistic comment
        f.write(f"// Output samples represent the {stat_name} of each subblock\n")
        blk = 0
        cnNum = 0
        if not flag_per_chan_stats:
            for i in range(output_block_size):
                ranges = []
                for ch in range(num_channels * numBlocks):
                    start = ch * input_block_size + i * subblock_size
                    end = start + subblock_size - 1
                    ranges.append(f"Channel {chNum} [{start}:{end}]")
                f.write(
                    f"// Subblock {i} block {blk}: {stat_name} over {' and '.join(ranges)}\n"
                )
                if chNum < num_channels * numBlocks - 1:
                    chNum = chNum + 1
                    if chNum > num_channels - 1:
                        blk = blk + 1
                        chNum = 0
        else:
            for ch in range(num_channels * numBlocks):
                for i in range(output_block_size):
                    start = ch * input_block_size + i * subblock_size
                    end = start + subblock_size - 1
                    f.write(
                        f"// Subblock {i} for Channel {chNum} of block {blk}: {stat_name} over [{start}:{end}]\n"
                    )
                if chNum < num_channels * numBlocks - 1:
                    chNum = chNum + 1
                    if chNum > num_channels - 1:
                        blk = blk + 1
                        chNum = 0

        f.write(f"#ifdef WIN32\n")
        f.write(
            f"{c_data_type} staticRefOutCase{test_id}[{output_block_size * output_num_channels}] =\n"
        )
        f.write(f"#else\n")
        f.write(
            f'__attribute__((section(".staticData"))) static {c_data_type} staticRefOutCase{test_id}[{output_block_size * output_num_channels}] =\n'
        )
        f.write(f"#endif\n")
        f.write("{\n")
        for i, val in enumerate(output_signal):
            f.write(f"    {format_spec % val}")
            f.write("," if i < len(output_signal) - 1 else "")
            f.write("\n" if (i + 1) % 8 == 0 or i == len(output_signal) - 1 else "")
        f.write("\n};\n")

