def generate_sine(num_samples, sampling_rate, frequency, amplitude):
    """Generate a continuous sine wave for all numBlocks of a given channel.

    Args:
        num_samples (int): Number of samples per frame.
        sampling_rate (int): Sampling rate in Hz.
        channel (int): Channel index (for phase offset if needed).
        frequency (float, optional): Frequency of the sine wave in Hz. Defaults to 2000.0 Hz.
        amplitude (float, optional): Amplitude of the sine wave. Defaults to 1.0.

    Returns:
        numpy.ndarray: Array of sine wave samples, shape (num_samples * num_frames,).
    """
    t = np.linspace(0, num_samples / sampling_rate, num_samples, endpoint=False)
    sine_wave = amplitude * np.sin(2 * np.pi * frequency * t)
    return sine_wave


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    numSamples = currPrm["numSamples"]
    startFrequency = currPrm["startFrequency"]
    targetFrequency = currPrm["targetFrequency"]
    startPhase = currPrm["startPhase"]
    smoothingTime = currPrm["smoothingTime"]
    samplingRate = currPrm["samplingRate"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    C7100 = currPrm["C7100"]
    numBlocks = currPrm["numBlocks"]
    executionModeStr = currPrm["executionMode"]

    if testType in ["STATIC"]:
        out = "staticRefOutCase" + testId
    else:
        out = "NULL"

    if C7100 == "FALSE":
        testParamsFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )
    # Convert executionMode string to integer for C code
    if executionModeStr.upper() == "SCALAR":
        executionModeInt = 0
    else:  # Default to VECTOR if not SCALAR
        executionModeInt = 1

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Output buffer \n" % ((out)))
    idatFile.write("%s, // numSamples \n" % ((numSamples)))
    idatFile.write("%s, // startFrequency \n" % ((startFrequency)))
    idatFile.write("%s, // targetFrequency \n" % ((targetFrequency)))
    idatFile.write("%s, // startPhase \n" % ((startPhase)))
    idatFile.write("%s, // smoothingTime \n" % ((smoothingTime)))
    idatFile.write("%s, // samplingRate \n" % ((samplingRate)))
    idatFile.write("%d, // executionMode (1=VECTOR, 0=SCALAR)\n" % (executionModeInt))
    idatFile.write("%s, // precision \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("%d, // numBlocks\n" % int(numBlocks))

    idatFile.write("},\n")
    idatFile.write("#endif\n")

    if C7100 == "FALSE":
        testParamsFile.write("#endif // if !defined(__C7100__)\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_sinusoidGenerator_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_sinusoidGenerator_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["numSamples"] = int(testCase["numSamples"])
    testCase["startFrequency"] = float(testCase["startFrequency"])
    testCase["targetFrequency"] = float(testCase["targetFrequency"])
    testCase["startPhase"] = float(testCase["startPhase"])
    testCase["smoothingTime"] = float(testCase["smoothingTime"])
    testCase["samplingRate"] = int(testCase["samplingRate"])
    testCase["numBlocks"] = int(testCase.get("numBlocks", 1))
    testCase["executionMode"] = testCase.get("executionMode", "VECTOR").strip()
    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    dType = testCase["dType"]
    numSamples = testCase["numSamples"]
    startFrequency = testCase["startFrequency"]
    targetFrequency = testCase["targetFrequency"]
    startPhase = testCase["startPhase"]
    smoothingTime = testCase["smoothingTime"]
    sampling_rate = testCase["samplingRate"]
    plotSignals = testCase["plotSignals"]
    numBlocks = testCase["numBlocks"]

    # --- Use numpy float32 consistently ---
    target_dtype = np.float32 if dType == "AUDIOLIB_FLOAT32" else np.float64

    # Calculate total samples across all numBlocks
    totalSamples = numSamples * numBlocks

    # Allocate output array with the target type directly
    out = np.zeros((totalSamples), dtype=target_dtype)

    # --- Define constants with target precision ---
    TWO_PI = target_dtype(2.0 * np.pi)
    PI = target_dtype(np.pi)
    sampling_rate_f = target_dtype(sampling_rate)  # Use float version for calculations

    # --- Calculate initial parameters with target precision ---
    # Convert degrees to radians
    phase = target_dtype(startPhase * PI / 180.0)
    phaseIncTarget = target_dtype(TWO_PI * targetFrequency / sampling_rate_f)
    phaseInc = target_dtype(TWO_PI * startFrequency / sampling_rate_f)

    # Calculate smoothing coefficient carefully, handle smoothingTime == 0
    if smoothingTime > 0:
        # Normal smoothing path
        phaseInc = target_dtype(TWO_PI * startFrequency / sampling_rate_f)
        smoothingCoeff = target_dtype(
            1.0 - np.exp(-1.0 / (sampling_rate_f * smoothingTime / 1000.0))
        )
        oneMinusRate = target_dtype(1.0) - smoothingCoeff
    else:
        phaseInc = (
            phaseIncTarget  # Start frequency is ignored, phaseInc is set to target
        )
        smoothingCoeff = target_dtype(1.0)
        oneMinusRate = target_dtype(0.0)

    oneMinusRate = target_dtype(1.0) - smoothingCoeff

    # --- Initialize loop variables with target precision ---
    localAmp = phaseInc
    localPhase = phase
    MAX_VAL = target_dtype(1048576.0)

    # --- Simulation loop mimicking C's single-precision steps ---
    for i in range(totalSamples):
        # Calculate sine using the current phase
        # np.sin should respect the dtype of localPhase for its calculation and output
        if np.abs(localPhase) > MAX_VAL:
            out[i] = target_dtype(0.0)
        else:
            out[i] = np.sin(localPhase)

        # Update phase for the *next* sample, casting intermediate result
        localPhase = target_dtype(localPhase + localAmp)

        # Wrap phase if necessary, casting intermediate result
        # Using a loop for potential multiple wraps, although unlikely per sample
        if localPhase >= TWO_PI:
            localPhase = target_dtype(localPhase - TWO_PI)

        # Update phase increment (smoothing) for the *next* sample, casting intermediate result
        localAmp = target_dtype(
            localAmp * oneMinusRate + phaseIncTarget * smoothingCoeff
        )

    if plotSignals == "TRUE":
        file_io.plot_Signals(out, totalSamples, testId)

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


