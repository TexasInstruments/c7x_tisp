def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    srcSamples = testCase["srcSamples"]
    tableSamples = testCase["tableSamples"]
    maxVal = float(testCase["maxVal"])
    minVal = float(testCase["minVal"])
    testType = testCase["testType"]
    numBlocks = testCase["numBlocks"]

    [minVal, maxVal] = [minVal, maxVal]

    src = np.random.uniform(low=minVal - 10, high=maxVal, size=srcSamples * numBlocks)
    table = np.random.uniform(low=minVal - 10, high=maxVal, size=tableSamples)

    dst = tableInterpolateProcess(src, table, minVal, maxVal, tableSamples)

    # Write header file with flattened 1D inputs, outputs, and gains
    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(
        in0=src, in1=table, out=dst, testCase=testCase, headerFileName=headerFileName
    )

    # Return min and max across both left and right output channels
    min_output = np.min(dst)
    max_output = np.max(dst)
    return [min_output, max_output]


