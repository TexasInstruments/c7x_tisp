# dtype mapping for CSV dType values
DTYPE_MAP = {
    "float": np.float32,
    "FLOAT": np.float32,
}


def get_soc_guard(am275_soc_value, testId):
    """Generate SOC preprocessor guard based on 'AM275 SOC' column value and specific test constraints"""
    guard_clauses = []

    if str(am275_soc_value).lower() != "yes":
        guard_clauses.append("!(SOC == AM275 && !defined(HOST_EMULATION))")

    # Hardcoded exclusion for Test 8 on AM62D due to 800KB L2 heap limit
    if str(testId) == "8":
        guard_clauses.append("!(SOC == AM62D && !defined(HOST_EMULATION))")

    if not guard_clauses:
        return None

    return " && ".join(guard_clauses)


def generate_sine(
    num_samples, sampling_rate, num_frames, channel, frequency, amplitude
):
    """Generate a continuous sine wave for all frames of a given channel."""
    total_samples = int(num_samples) * int(num_frames)
    # exact spacing
    t = np.arange(total_samples, dtype=np.float64) / float(sampling_rate)
    sine_wave = amplitude * np.sin(2.0 * np.pi * frequency * t + channel * np.pi / 4.0)
    return sine_wave


def gen_testCaseParams(idatFile, currPrm):
    """Generate and write test case parameters to idat file."""
    testId = currPrm["ID"]
    dType = currPrm["dType"]
    numSamples = currPrm["numSamples"]
    numChannels = currPrm["numChannels"]
    samplingRate = currPrm["samplingRate"]
    filterLength = currPrm["filterLength"]
    stepSize = currPrm["stepSize"]
    strideIn0 = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    numBlocks = currPrm["numBlocks"]
    plotSignals = currPrm["plotSignals"]
    waveFiles = currPrm["waveFiles"]
    amplitude = currPrm["amplitude"]
    frequency = currPrm["frequency"]
    blockWidth = currPrm["blockWidth"]
    blockHeight = currPrm["blockHeight"]
    isInterleaved = int(currPrm.get("isInterleaved", 0))
    am275_soc = currPrm.get("AM275 SOC", "yes")

    AUDIOLIB_dType = TISP_utils.resolve_AUDIOLIB_dType(dType)

    if testType in ["STATIC", "SINE"]:
        testTypeOut = "STATIC"
        in_signal = f"staticRefInCase{testId}"
        desired_signal = f"staticRefDesiredCase{testId}"
        out_signal = f"staticRefOutCase{testId}"
        coefficients = f"staticRefCoeffCase{testId}"
    else:
        testTypeOut = testType
        in_signal = "NULL"
        desired_signal = "NULL"
        out_signal = "NULL"
        coefficients = "NULL"

    idatFile.write("#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % int(testId))
    soc_guard = get_soc_guard(am275_soc, testId)
    if soc_guard:
        idatFile.write("#if %s\n" % soc_guard)
    idatFile.write("{\n")
    idatFile.write("%s, // Test Pattern\n" % testTypeOut)
    idatFile.write("%s, // Input Signal\n" % in_signal)
    idatFile.write("%s, // Desired Signal\n" % desired_signal)
    idatFile.write("%s, // Output Signal\n" % out_signal)
    idatFile.write("%s, // Filter Coefficients\n" % coefficients)
    idatFile.write("%s, // Sample Data Type\n" % AUDIOLIB_dType)
    idatFile.write("%d, // Samples per channel\n" % int(numSamples))
    idatFile.write("%d, // Number of Channels\n" % int(numChannels))
    idatFile.write("%d, // isInterleaved\n" % isInterleaved)
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn0 \n"
        % (strideIn0, dType)
    )
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
        % (strideOut, dType)
    )
    idatFile.write("%d, // Filter Length\n" % int(filterLength))
    idatFile.write("%f, // Step Size\n" % float(stepSize))
    idatFile.write("%s, // blockWidth \n" % ((blockWidth)))
    idatFile.write("%s, // blockHeight \n" % ((blockHeight)))
    idatFile.write("%d, // Number of Executions\n" % int(numBlocks))
    idatFile.write("%d, // Test ID\n" % int(testId))
    idatFile.write("},\n")
    if soc_guard:
        idatFile.write("#endif  // SOC guard\n")
    idatFile.write("#endif  // TEST_CASE guard\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file."""
    header_path = os.path.join("..", "common", "ti_lice_header_idat.txt")
    if os.path.exists(header_path):
        with open(header_path, "r") as fIn:
            lines = fIn.readlines()
        idatFile.writelines(lines)
    else:
        idatFile.write(
            "/* autogenerated idat header - original header file missing */\n"
        )

    includeString = '#include "TISP_nlms_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    for testCase in testCases:
        if testCase["testType"] in ["STATIC", "SINE"]:
            TISP_utils.gen_ifdefs(idatFile, testCase)
    idatFile.write("static TISP_nlms_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")
    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)
    idatFile.write("};\n\n")
    func_path = "test_param_function.txt"
    if os.path.exists(func_path):
        with open(func_path, "r") as fIn:
            lines = fIn.readlines()
        idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert string parameters to appropriate types and add derived fields."""
    # canonicalize fields and types
    testCase["ID"] = testCase.get("ID", testCase.get("testId", "0"))
    testCase["testId"] = int(testCase["ID"])
    testCase["numSamples"] = int(testCase.get("numSamples", 0))
    testCase["numChannels"] = int(testCase.get("numChannels", 1))
    testCase["samplingRate"] = int(testCase.get("samplingRate", 48000))
    testCase["filterLength"] = int(testCase.get("filterLength", 16))
    testCase["stepSize"] = float(testCase.get("stepSize", 0.1))

    # strides (support alternate column names)
    if "strideInElements" in testCase:
        testCase["strideInElements"] = int(testCase["strideInElements"])
    else:
        testCase["strideInElements"] = int(
            testCase.get("strideIn0", testCase["numSamples"])
        )

    if "strideOutElements" in testCase:
        testCase["strideOutElements"] = int(testCase["strideOutElements"])
    else:
        testCase["strideOutElements"] = int(
            testCase.get("strideOut", testCase["numSamples"])
        )

    testCase["numBlocks"] = int(testCase.get("numBlocks", 1))
    testCase["plotSignals"] = (
        str(testCase.get("plotSignals", "FALSE")).upper() == "TRUE"
    )
    testCase["waveFiles"] = str(testCase.get("waveFiles", "FALSE")).upper() == "TRUE"
    testCase["amplitude"] = float(testCase.get("amplitude", 1.0))
    testCase["frequency"] = float(testCase.get("frequency", 2000.0))
    testCase["dType"] = str(testCase.get("dType", "float")).lower()
    testCase["isInterleaved"] = int(testCase.get("isInterleaved", 0))
    if testCase["dType"] not in ("float", "double"):
        testCase["dType"] = "float"
    testCase["dtype_np"] = DTYPE_MAP[testCase["dType"]]
    testCase["blockWidth"] = int(testCase["blockWidth"])
    testCase["blockHeight"] = int(testCase["blockHeight"])
    testCase["testType"] = str(testCase.get("testType", "STATIC")).upper()
    return testCase


def gen_test_case_header_file(testCase):
    testId = testCase["ID"]
    numSamples = testCase["numSamples"]
    numChannels = testCase["numChannels"]
    samplingRate = testCase["samplingRate"]
    filterLength = testCase["filterLength"]
    stepSize = testCase["stepSize"]
    testType = testCase["testType"]
    numBlocks = testCase["numBlocks"]
    plotSignals = testCase["plotSignals"]
    waveFiles = testCase["waveFiles"]
    amplitude = testCase["amplitude"]
    frequency = testCase["frequency"]
    dtype_np = testCase["dtype_np"]
    isInterleaved = int(testCase.get("isInterleaved", 0))
    blockWidth = testCase["blockWidth"]
    blockHeight = testCase["blockHeight"]

    if isInterleaved:
        numBlocks = numSamples / blockHeight
    else:
        numBlocks = numSamples / blockWidth

    frames = int(numBlocks)
    samplesPerFrame = int(blockWidth) * int(blockHeight)

    # Always use 2D shape: (frames, samplesPerFrame)
    pInSignal = np.zeros((frames, samplesPerFrame), dtype=dtype_np)
    pDesiredSignal = np.zeros((frames, samplesPerFrame), dtype=dtype_np)
    pOutSignal = np.zeros((frames, samplesPerFrame), dtype=dtype_np)
    pCoefficients = np.zeros((numChannels, filterLength), dtype=dtype_np)

    # Generate input and desired signals
    for frame in range(frames):
        for sample_idx in range(blockWidth):
            for ch in range(blockHeight):
                if isInterleaved:
                    idx = sample_idx * blockHeight + ch
                else:
                    idx = ch * blockWidth + sample_idx

                if testType == "STATIC":
                    clean_val = np.random.uniform(-1.0, 1.0)
                elif testType == "SINE":
                    full_sine = generate_sine(
                        blockWidth, samplingRate, frames, ch, frequency, amplitude
                    )
                    clean_val = full_sine[frame * blockWidth + sample_idx]
                else:
                    clean_val = 0.0

                pDesiredSignal[frame, idx] = dtype_np(clean_val)
                noise = np.random.normal(0.0, 0.3)
                pInSignal[frame, idx] = dtype_np(clean_val + noise)

    if isInterleaved:
        # Flatten to 1D for interleaved NLMS function
        in_flat = pInSignal.flatten()
        desired_flat = pDesiredSignal.flatten()
        # total samples per channel = numSamples * frames
        # FIX: Pass numSamples as the block_size
        out_flat, coeffs_2d = nlms.nlms_filter_interleaved(
            in_flat,
            desired_flat,
            blockWidth,
            blockHeight * frames,
            filterLength,
            stepSize,
            blockHeight,
        )
        pOutSignal = out_flat.reshape((frames, samplesPerFrame))
        pCoefficients = coeffs_2d
    else:
        for ch in range(blockHeight):
            startIdx = ch * blockWidth
            endIdx = (ch + 1) * blockWidth
            in_ch = pInSignal[:, startIdx:endIdx].flatten()
            desired_ch = pDesiredSignal[:, startIdx:endIdx].flatten()
            out_ch, final_coeffs = nlms.nlms_filter(
                in_ch, desired_ch, filterLength, stepSize, blockWidth
            )
            pOutSignal[:, startIdx:endIdx] = out_ch.reshape(frames, blockWidth)
            pCoefficients[ch, :] = final_coeffs

    # Plot and write files
    if plotSignals:
        file_io.plot_signal_pair(
            pInSignal,
            pDesiredSignal,
            blockWidth,
            blockHeight,
            numBlocks,
            testId,
            "input_desired",
            channel=0,
            test_type=testType,
        )
        file_io.plot_signal_pair(
            pOutSignal,
            pDesiredSignal,
            blockWidth,
            blockHeight,
            numBlocks,
            testId,
            "output_desired",
            channel=0,
            test_type=testType,
        )

    if waveFiles:
        file_io.write_wav_files(
            pInSignal,
            pDesiredSignal,
            pOutSignal,
            pOutSignal,
            np.zeros_like(pInSignal),
            np.zeros_like(pInSignal),
            testCase,
            numBlocks,
        )

    # Flatten for header file
    in_list = pInSignal.flatten().tolist()
    desired_list = pDesiredSignal.flatten().tolist()
    out_list = pOutSignal.flatten().tolist()
    coeff_list = pCoefficients.flatten().tolist()

    headerFileName = f"staticRefCase{testId}.h"
    file_io.write_header_file(
        in_list, desired_list, out_list, coeff_list, testCase, headerFileName, numBlocks
    )

    return [float(np.min(out_list)), float(np.max(out_list))]


# CSV file with parameters for all test cases
testCasesCsvFile = "test_cases_list.csv"
testIdList = list(range(0, 100))

myArgs = TISP_utils.getCmdLineArgs()


def gen_test_case(testCase):
    if testCase["testType"] in ["STATIC", "SINE"]:
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            f"Test case generation completed for test ID {testCase['ID']} w/ min: {minY} and max {maxY}"
        )
    else:
        print(
            f"Skipping test case generation for test ID {testCase['ID']} as testType is not supported"
        )


# --- main flow ---
if not os.path.exists(testCasesCsvFile):
    raise FileNotFoundError(f"Test cases CSV not found: {testCasesCsvFile}")

with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)
    # preprocess list entries
    for i, testCase in enumerate(testCases):
        testCases[i] = process_test_case(testCase)
    for testCase in testCases:
        if myArgs.allCases or int(testCase["ID"]) in testIdList:
            gen_test_case(testCase)

idatFileName = "../../../../superNode/i2d_i2d_to_o2d/TISP_nlms_superNode/TISP_nlms_superNode_idat.cpp"
with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)

if platform == "linux" or platform == "linux2":
    try:
        call(["clang-format", "-style=file", "-i", idatFileName])
    except Exception:
        pass
    try:
        call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
        call(["rm", idatFileName + "~"])
    except Exception:
        pass

print("\nIdat file generation completed")
