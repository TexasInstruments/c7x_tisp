def get_soc_guard(am275_soc_value):
    """Generate SOC preprocessor guard based on 'AM275 SOC' column value"""
    if am275_soc_value.lower() == "yes":
        return None
    else:
        return "!(SOC == AM275 && !defined(HOST_EMULATION))"


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    dType = currPrm["dType"]
    inWidth = currPrm["inWidth"]
    inHeight = currPrm["inHeight"]
    strideIn = currPrm["strideIn"]
    numRows = currPrm["numRows"]
    numCols = currPrm["numCols"]
    isColSelect = currPrm["isColSelect"]
    isOutputInterleave = currPrm["isOutputInterleave"]
    blockWidth = currPrm["blockWidth"]
    outPitch = currPrm["outPitch"]
    alignStride = currPrm["alignStride"]
    testPattern = currPrm["testPattern"]

    testId = currPrm["ID"]
    am275_soc = currPrm.get("AM275 SOC", "yes")

    in0 = "staticRefIn0Case" + testId
    in1 = "staticRefIn1Case" + testId
    out = "staticRefOutCase" + testId

    testParamsFile.write(
        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
    )

    soc_guard = get_soc_guard(am275_soc)
    if soc_guard:
        idatFile.write("#if %s\n" % soc_guard)

    idatFile.write("{\n")
    idatFile.write("%s, // testPattern \n" % ((testPattern)))
    idatFile.write("%s, // *staticIn0 \n" % ((in0)))
    idatFile.write("%s, // *staticIn1 \n" % ((in1)))
    idatFile.write("%s, // *staticOut\n" % ((out)))
    idatFile.write("%s, // dataType \n" % ((TISP_utils.resolve_DSPLIB_dType(dType))))
    idatFile.write("%s, // inWidth \n" % ((inWidth)))
    idatFile.write("%s, // inHeight \n" % ((inHeight)))
    idatFile.write("%s * sizeof(int32_t), // strideIn \n" % ((strideIn)))
    idatFile.write("%s, // numRows \n" % ((numRows)))
    idatFile.write("%s, // numCols \n" % ((numCols)))
    idatFile.write("%s, // isColSelect \n" % ((isColSelect)))
    idatFile.write("%s, // isOutputInterleave \n" % ((isOutputInterleave)))
    idatFile.write("%s, // blockWidth \n" % ((blockWidth)))
    if alignStride == "FALSE":
        idatFile.write("%s * sizeof(%s), // strideOut \n" % ((outPitch, dType)))
    else:
        idatFile.write(
            "DSPLIB_CALC_STRIDE(%s * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
            % ((outPitch), (dType))
        )
    idatFile.write("%d // test ID\n" % int(testId))
    idatFile.write("},\n")
    if soc_guard:
        idatFile.write("#endif  // SOC guard\n")
    idatFile.write("#endif  // TEST_CASE guard\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_tableSourceRowColSelector_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_tableSourceRowColSelector_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["inWidth"] = int(testCase["inWidth"])
    testCase["inHeight"] = int(testCase["inHeight"])
    testCase["strideIn"] = int(testCase["strideIn"])
    testCase["numIndices"] = testCase["inWidth"] * testCase["inHeight"]
    testCase["numRows"] = int(testCase["numRows"])
    testCase["numCols"] = int(testCase["numCols"])
    testCase["isColSelect"] = int(testCase["isColSelect"])
    testCase["isOutputInterleave"] = int(testCase["isOutputInterleave"])
    testCase["blockWidth"] = int(testCase["blockWidth"])
    testCase["outPitch"] = int(testCase["outPitch"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    testId = testCase["ID"]
    dType = testCase["dType"]
    numIndices = testCase["numIndices"]
    numRows = testCase["numRows"]
    numCols = testCase["numCols"]
    isColSelect = testCase["isColSelect"]
    isOutputInterleave = testCase["isOutputInterleave"]

    # The frame is one block of numIndices indices, inHeight rows of inWidth indices in memory order
    kernel = TableSourceRowColSelector(
        num_indices=numIndices,
        num_rows=numRows,
        num_cols=numCols,
        is_col_select=isColSelect,
        is_output_interleave=isOutputInterleave,
        num_blocks=1,
        dtype=dType,
    )
    in0, in1 = kernel.generate_inputs()

    # The supernode runs the node once per tile of blockWidth indices, and the tiles of the output follow the tiles of
    # the input, so the reference is one table row or column per index of the frame: non-interleaved
    # (numIndices, selLen), interleaved (selLen, numIndices)
    out = kernel.execute(in0, in1)
    in0 = in0[0]

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, in1, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


