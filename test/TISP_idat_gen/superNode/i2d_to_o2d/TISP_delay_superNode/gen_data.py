def get_soc_guard(am275_soc_value):
    """Generate SOC preprocessor guard based on 'AM275 SOC' column value

    Args:
        am275_soc_value (str): Value from 'AM275 SOC' column (yes/no)

    Returns:
        str or None: Preprocessor guard condition, or None if no guard needed
    """
    if am275_soc_value.lower() == "yes":
        # No guard needed - runs on all builds
        return None
    else:
        # Exclude from AM275 SOC builds only (not HE, not AM62D)
        return "!(SOC == AM275 && !defined(HOST_EMULATION))"


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    testId = currPrm["ID"]
    dType = currPrm["dType"]
    mode = currPrm["mode"]
    delaySize = currPrm["delaySize"]
    interleave = currPrm["interleave"]
    numChannels = currPrm["numChannels"]
    numSamples = currPrm["numSamples"]
    strideIn = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testPattern = currPrm["testPattern"]
    blockWidth = currPrm["blockWidth"]
    blockHeight = currPrm["blockHeight"]
    am275_soc = currPrm.get("AM275 SOC", "yes")  # Default to yes if column missing

    inputBuff = "staticRefInCase" + testId
    outputBuff = "staticRefOutCase" + testId
    delayBuff = "staticUpdatedDelayCase" + testId

    testParamsFile.write(
        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
    )

    # Add SOC-specific guard only if AM275 SOC = no
    soc_guard = get_soc_guard(am275_soc)
    if soc_guard:
        idatFile.write("#if %s\n" % soc_guard)

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testPattern)))
    idatFile.write("%s, // delaySize \n" % ((delaySize)))
    idatFile.write("%s, // precision \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // mode \n" % ((mode)))
    idatFile.write("%s, // Input buffer\n" % ((inputBuff)))
    idatFile.write("%s, // Output buffer \n" % ((outputBuff)))
    idatFile.write("%s, // updatedDelay buffer \n" % ((delayBuff)))
    idatFile.write("%s, // Interleave \n" % ((interleave)))
    idatFile.write("%s, // numChannels \n" % ((numChannels)))
    idatFile.write("%s, // numSamples \n" % ((numSamples)))
    idatFile.write(
        "%s * sizeof(%s), // stride of input buffer \n" % ((strideIn), (dType))
    )
    idatFile.write(
        "%s * sizeof(%s), // stride of output buffer \n" % ((strideOut), (dType))
    )
    idatFile.write("%s, // blockWidth \n" % ((blockWidth)))
    idatFile.write("%s, // blockHeight \n" % ((blockHeight)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    if soc_guard:
        idatFile.write("#endif  // SOC guard\n")
    idatFile.write("#endif  // TEST_CASE guard\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_delay_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_delay_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """
    # print(testCase.keys())
