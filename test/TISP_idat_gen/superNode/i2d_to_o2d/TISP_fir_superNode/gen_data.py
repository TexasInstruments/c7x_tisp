def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testType = currPrm["testType"]
    dTypeIn = currPrm["dTypeIn"]
    dTypeOut = currPrm["dTypeOut"]
    dTypeFilter = currPrm["dTypeFilter"]
    dataSize = currPrm["dataSize"]
    filterSize = currPrm["filterSize"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]
    enableNChCoefs = currPrm["enableNChCoefs"]
    enableMMA = currPrm["enableMMA"]
    enableQ = currPrm["enableQ"]
    Q = currPrm["Q"]
    testId = currPrm["ID"]
    batchSize = currPrm["batchSize"]
    outSize = dataSize
    pitchX = currPrm["pitchX"]
    pitchH = currPrm["pitchH"]
    pitchY = currPrm["pitchY"]
    numBlocks = currPrm["numBlocks"]

    if testType == "STATIC":
        inputData = "staticRefInCase" + testId
        filterData = "staticRefFilterCase" + testId
        outputData = "staticRefOutCase" + testId
    else:
        inputData = "NULL"
        filterData = "NULL"
        outputData = "NULL"

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    DSPLIB_dTypeIn = TISP_utils.resolve_DSPLIB_dType(dTypeIn)
    DSPLIB_dTypeFilter = TISP_utils.resolve_DSPLIB_dType(dTypeFilter)

    if dTypeIn == "int8_t" or dTypeIn == "uint8_t":
        sizeBytes = 1
    elif dTypeIn == "int16_t" or dTypeIn == "uint16_t":
        sizeBytes = 2
    elif dTypeIn == "int32_t" or dTypeIn == "uint32_t" or dTypeIn == "float":
        sizeBytes = 4
    else:
        sizeBytes = 8

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Input vector \n" % ((inputData)))
    idatFile.write("%s, // Filter vector \n" % ((filterData)))
    idatFile.write("%s, // Output vector \n" % ((outputData)))
    idatFile.write("%s, // datatype \n" % ((DSPLIB_dTypeIn)))
    idatFile.write("%s, // dataSize \n" % ((dataSize)))
    idatFile.write("%s, // numBlocks \n" % ((numBlocks)))
    idatFile.write("%s, // dataPitchIn \n" % (pitchX))
    idatFile.write("%s, // dataPitchOut \n" % (pitchY))
    idatFile.write("%s, // batchSize \n" % ((batchSize)))
    idatFile.write("%s, // filterSize \n" % ((filterSize)))
    idatFile.write("%s, // filterPitch \n" % (pitchH))
    idatFile.write("%s, // enableNchCoefs\n" % ((enableNChCoefs)))
    idatFile.write("%s, // enableMMA \n" % ((enableMMA)))
    idatFile.write("%s, // enableQ \n" % ((enableQ)))
    idatFile.write("%s, // Q \n" % ((Q)))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif")
    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_fir_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_fir_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["dataSize"] = int(testCase["dataSize"])
    testCase["filterSize"] = int(testCase["filterSize"])
    testCase["enableMMA"] = int(testCase["enableMMA"])
    testCase["enableNChCoefs"] = int(testCase["enableNChCoefs"])
    testCase["batchSize"] = int(testCase["batchSize"])
    testCase["enableQ"] = int(testCase["enableQ"])
    testCase["Q"] = int(testCase["Q"])
    testCase["pitchX"] = int(testCase["pitchX"])
    testCase["pitchY"] = int(testCase["pitchY"])
    testCase["pitchH"] = int(testCase["pitchH"])
    testCase["stateSize"] = int(testCase["stateSize"])
    testCase["numBlocks"] = int(testCase["numBlocks"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    dataSize = testCase["dataSize"]
    dTypeIn = testCase["dTypeIn"]
    filterSize = testCase["filterSize"]
    dTypeFilter = testCase["dTypeFilter"]
    filterSize = testCase["filterSize"]
    batchSize = testCase["batchSize"]
    enableNChCoefs = testCase["enableNChCoefs"]
    stateSize = testCase["stateSize"]
    numBlocks = testCase["numBlocks"]

    if dTypeIn == "int8_t" or dTypeIn == "uint8_t":
        bits = 8
    elif dTypeIn == "int16_t" or dTypeIn == "uint16_t":
        bits = 16
    elif dTypeIn == "int32_t" or dTypeIn == "uint32_t" or dTypeIn == "float":
        bits = 32
    else:
        bits = 64

    # unsigned integer
    if dTypeIn[0] == "u":
        minVal = 0
        maxVal = (2**bits) - 1
    else:
        minVal = -(2 ** (bits - 1))
        maxVal = 2 ** (bits - 1)

    # determine filter height
    if enableNChCoefs == 1:
        filterHeight = batchSize
    else:
        filterHeight = 1

    if dTypeIn == "int8_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("int8")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("int8")
    elif dTypeIn == "int16_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("int16")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("int16")
    elif dTypeIn == "int32_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("int32")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("int32")
    elif dTypeIn == "int64_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("int64")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("int64")
    elif dTypeIn == "uint8_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("uint8")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("uint8")
    elif dTypeIn == "uint16_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("uint16")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("uint16")
    elif dTypeIn == "uint32_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("uint32")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("uint32")
    elif dTypeIn == "uint64_t":
        inputData = np.random.uniform(
            low=minVal, high=maxVal, size=(batchSize, (dataSize * numBlocks))
        ).astype("uint64")
        filterData = np.random.uniform(
            low=minVal, high=maxVal, size=(filterHeight, filterSize)
        ).astype("uint64")
    elif dTypeIn == "float":
        inputData = np.random.uniform(
            low=-1, high=1, size=(batchSize, (dataSize * numBlocks))
        ).astype("float")
        filterData = np.random.uniform(
            low=-1, high=1, size=(filterHeight, filterSize)
        ).astype("float")
        stateData = np.zeros(
            (batchSize, (dataSize * numBlocks + filterSize - 1))
        ).astype("float")
    elif dTypeIn == "double":
        inputData = np.random.uniform(
            low=-1, high=1, size=(batchSize, (dataSize * numBlocks))
        ).astype("double")
        filterData = np.random.uniform(
            low=-1, high=1, size=(filterHeight, filterSize)
        ).astype("double")
        stateData = np.zeros(
            (batchSize, (dataSize * numBlocks + filterSize - 1))
        ).astype("double")
    # # normalize coefficients
    # filterSum = np.sum(np.abs(filterData), axis=1)
    # filterNorm = filterData / filterSum[:, None]
    # filterData = filterNorm

    filterData = filterData[:, ::-1]
    myFIR = FIR()
    outputData = myFIR.execute(
        inputData,
        stateData,
        filterData,
        batchSize,
        dataSize,
        filterSize,
        numBlocks,
        enableNChCoefs,
    )

    headerFileName = f"../../../../superNode/i2d_to_o2d/TISP_fir_superNode/test_data/staticRefCase{str(testId)}.h"
    tensor_to_cpp_header = TensorToCppHeader(headerFileName, mode="new")
    tensor_to_cpp_header.write_tensor_to_header(
        inputData, f"staticRefInCase{str(testId)}", "float"
    )
    tensor_to_cpp_header.write_tensor_to_header(
        filterData, f"staticRefFilterCase{str(testId)}", "float"
    )
    tensor_to_cpp_header.write_tensor_to_header(
        outputData, f"staticRefOutCase{str(testId)}", "float"
    )

    return [np.min(outputData), np.max(outputData)]


