def generate_sine(num_samples, sampling_rate, frequency, amplitude):
    """Generate a continuous sine wave for all numExecReps of a given channel.

    Args:
        num_samples (int): Number of samples per frame.
        sampling_rate (int): Sampling rate in Hz.
        channel (int): Channel index (for phase offset if needed).
        frequency (float, optional): Frequency of the sine wave in Hz. Defaults to 2000.0 Hz.
        amplitude (float, optional): Amplitude of the sine wave. Defaults to 1.0.

    Returns:
        numpy.ndarray: Array of sine wave samples, shape (num_samples * num_frames,).
    """
    t = np.linspace(0, num_samples / sampling_rate, num_samples, endpoint=False)
    sine_wave = amplitude * np.sin(2 * np.pi * frequency * t)
    return sine_wave


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    dType = currPrm["dType"]
    widthIn = currPrm["widthIn"]
    heightIn = currPrm["heightIn"]
    blockWidth = currPrm["blockWidth"]
    blockHeight = currPrm["blockHeight"]
    inPitch = currPrm["inPitch"]
    outPitch = currPrm["outPitch"]
    threshold = currPrm["threshold"]
    endKnee = currPrm["endKnee"]
    samplingRate = currPrm["samplingRate"]
    frequency = currPrm["frequency"]
    amplitude = currPrm["amplitude"]
    plotSignals = currPrm["plotSignals"]
    testType = currPrm["testType"]
    testId = currPrm["ID"]

    if testType in ["STATIC", "SINE"]:
        in0 = "staticRefIn0Case" + testId
        out = "staticRefOutCase" + testId
        testType = "STATIC"

    testParamsFile.write(
        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
    )

    idatFile.write("{\n")
    idatFile.write("%s, // testPattern \n" % ((testType)))
    idatFile.write("%s, // *staticIn \n" % ((in0)))
    idatFile.write("%s, // *staticOut\n" % ((out)))
    idatFile.write("%s, // dataType \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // widthIn \n" % ((widthIn)))
    idatFile.write("%s, // heightIn \n" % ((heightIn)))
    idatFile.write("%s, // blockWidth \n" % ((blockWidth)))
    idatFile.write("%s, // blockHeight \n" % ((blockHeight)))
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn0 \n"
        % ((inPitch), (dType))
    )
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
        % ((outPitch), (dType))
    )
    idatFile.write("%s, // threshold \n" % ((threshold)))
    idatFile.write("%s, // endKnee \n" % ((endKnee)))
    idatFile.write("%d // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_softClip_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] in ["STATIC", "SINE"]:
            TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_softClip_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["widthIn"] = int(testCase["widthIn"])
    testCase["heightIn"] = int(testCase["heightIn"])
    testCase["blockWidth"] = int(testCase["blockWidth"])
    testCase["blockHeight"] = int(testCase["blockHeight"])
    testCase["inPitch"] = int(testCase["inPitch"])
    testCase["outPitch"] = int(testCase["outPitch"])
    testCase["threshold"] = float(testCase["threshold"])
    testCase["endKnee"] = float(testCase["endKnee"])
    testCase["samplingRate"] = int(testCase["samplingRate"])
    testCase["frequency"] = float(testCase["frequency"])
    testCase["amplitude"] = float(testCase["amplitude"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    testId = testCase["ID"]
    dType = testCase["dType"]
    widthIn = testCase["widthIn"]
    heightIn = testCase["heightIn"]
    threshold = testCase["threshold"]
    endKnee = testCase["endKnee"]
    sampling_rate = testCase["samplingRate"]
    frequency = testCase["frequency"]
    amplitude = testCase["amplitude"]
    plotSignals = testCase["plotSignals"]

    [minVal, maxVal] = [-10, 10]

    in0 = np.zeros((heightIn, widthIn)).astype("float32")
    out = np.zeros((heightIn, widthIn)).astype("float32")
    if testCase["testType"] == "STATIC":
        in0 = np.random.uniform(
            low=minVal, high=maxVal, size=(heightIn, widthIn)
        ).astype("float32")
    elif testCase["testType"] == "SINE":
        for i in range(heightIn):
            in0[i * widthIn : (i + 1) * widthIn] = generate_sine(
                widthIn, sampling_rate, frequency, amplitude
            )

    absIN = np.abs(in0)
    mask_linear = absIN <= threshold

    out[mask_linear] = in0[mask_linear]
    mask_soft = ~mask_linear

    out_soft = (absIN[mask_soft] - threshold) / (
        absIN[mask_soft] - 2 * threshold + endKnee
    )
    out_soft = (endKnee - threshold) * out_soft + threshold
    out[mask_soft] = np.sign(in0[mask_soft]) * out_soft
    if plotSignals == "TRUE":
        file_io.plot_Signals(in0, out, widthIn, heightIn, testId)

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


