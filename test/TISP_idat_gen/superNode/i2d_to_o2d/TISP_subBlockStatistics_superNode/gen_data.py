def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    testId = currPrm["ID"]
    dType = currPrm["sampleDataType"]
    inChannels = currPrm["numChannels"]
    inSamples = currPrm["inputBlockSize"]
    subBlockSize = currPrm["subBlockSize"]
    strideIn = currPrm["strideIn"]
    strideOut = currPrm["strideOut"]
    statisticsType = currPrm["statisticsType"]
    flagPerChanStats = currPrm["flagPerChanStats"]
    testType = currPrm["testType"]
    blockWidth = currPrm["blockWidth"]
    blockHeight = currPrm["blockHeight"]

    in0 = "staticRefInCase" + testId
    out = "staticRefOutCase" + testId

    testParamsFile.write(
        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
    )

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Input buffer\n" % ((in0)))
    idatFile.write("%s, // Output buffer \n" % ((out)))
    idatFile.write("%s, // inputBlockSize \n" % ((inSamples)))
    idatFile.write("%s, // subBlockSize \n" % ((subBlockSize)))
    idatFile.write("%s, // numChannels \n" % ((inChannels)))
    idatFile.write("%s, // statisticsType \n" % ((statisticsType)))
    idatFile.write("%d, // flagPerChanStats \n" % (1 if flagPerChanStats else 0))
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn \n"
        % ((strideIn), (dType))
    )
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
        % ((strideOut), (dType))
    )
    idatFile.write("%s, // precision \n" % ((TISP_utils.resolve_AUDIOLIB_dType(dType))))
    idatFile.write("%s, // blockWidth \n" % ((blockWidth)))
    idatFile.write("%s, // blockHeight \n" % ((blockHeight)))
    idatFile.write("%d // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_subBlockStatistics_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write(
        "static TISP_subBlockStatistics_superNode_testParams_t testParams[] =  "
    )
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def compute_statistic(data, statistics_type):
    """Compute the specified statistic over the data.

    Args:
        data (numpy.ndarray): Flattened subblock data.
        statistics_type (int): Statistic to compute (0=max, 1=min, 2=max_abs, 3=mean, 4=rms, 5=std, 6=variance, 7=avg_energy, 8=sum, 9=sum_squares).

    Returns:
        float: Computed statistic.
    """
    if data.size == 0:
        return 0.0
    if statistics_type == 0:  # Maximum
        return np.max(data)
    elif statistics_type == 1:  # Minimum
        return np.min(data)
    elif statistics_type == 2:  # Maximum Absolute Value
        return np.max(np.abs(data))
    elif statistics_type == 3:  # Mean
        return np.mean(data)
    elif statistics_type == 4:  # RMS
        return np.sqrt(np.mean(data**2))
    elif statistics_type == 5:  # Standard Deviation
        return np.std(data)
    elif statistics_type == 6:  # Variance
        return np.var(data)
    elif statistics_type == 7:  # Average Energy
        return np.mean(data**2)
    elif statistics_type == 8:  # Sum
        return np.sum(data)
    elif statistics_type == 9:  # Sum of Squares
        return np.sum(data**2)
    else:
        raise ValueError(f"Invalid statistics_type: {statistics_type}")


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["sampleDataType"] = testCase["sampleDataType"]
    testCase["inputBlockSize"] = int(testCase["inputBlockSize"])
    testCase["subBlockSize"] = int(testCase["subBlockSize"])
    testCase["numChannels"] = int(testCase["numChannels"])
    testCase["strideIn"] = int(testCase["strideIn"])
    testCase["statisticsType"] = int(testCase["statisticsType"])
    testCase["testType"] = testCase["testType"]
    testCase["flagPerChanStats"] = testCase["flagPerChanStats"].upper() == "TRUE"
    testCase["blockWidth"] = int(testCase["blockWidth"])
    testCase["blockHeight"] = int(testCase["blockHeight"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    testId = testCase["testId"]
    inputBlockSize = testCase["inputBlockSize"]
    subBlockSize = testCase["subBlockSize"]
    numChannels = testCase["numChannels"]
    statisticsType = testCase["statisticsType"]
    testType = testCase["testType"]
    flagPerChanStats = testCase["flagPerChanStats"]
    dataType = testCase["sampleDataType"]

    # Calculate output block size and output channels
    outputBlockSize = inputBlockSize // subBlockSize
    outputNumChannels = numChannels if flagPerChanStats else 1
    totalInputSamples = inputBlockSize * numChannels
    totalOutputSamples = outputBlockSize * outputNumChannels

    # Generate input signal in planar format [ch0_samples, ch1_samples, ...]
    if dataType == "double":
        inputSignal = np.zeros(totalInputSamples, dtype=np.float64)
    else:
        inputSignal = np.zeros(totalInputSamples, dtype=np.float32)
    for ch in range(numChannels):
        startIdx = ch * inputBlockSize
        if dataType == "double":
            inputSignal[startIdx : startIdx + inputBlockSize] = np.random.uniform(
                low=-1.0, high=1.0, size=inputBlockSize
            ).astype(np.float64)
        else:
            inputSignal[startIdx : startIdx + inputBlockSize] = np.random.uniform(
                low=-1.0, high=1.0, size=inputBlockSize
            ).astype(np.float32)
    inputSignalFlat = inputSignal  # Already flat

    # Compute statistics for each subblock
    if dataType == "double":
        outputSignal = np.zeros(totalOutputSamples, dtype=np.float64)
    else:
        outputSignal = np.zeros(totalOutputSamples, dtype=np.float32)

    if flagPerChanStats:
        # Per-channel statistics
        for ch in range(numChannels):
            for i in range(outputBlockSize):
                startIdx = ch * inputBlockSize + i * subBlockSize
                endIdx = startIdx + subBlockSize
                channel_data = inputSignal[startIdx:endIdx]
                outputSignal[ch * outputBlockSize + i] = compute_statistic(
                    channel_data, statisticsType
                )
    else:
        # All-channel statistics
        for i in range(outputBlockSize):
            subblockData = []
            for ch in range(numChannels):
                startIdx = ch * inputBlockSize + i * subBlockSize
                endIdx = startIdx + subBlockSize
                subblockData.extend(inputSignal[startIdx:endIdx])
            if dataType == "double":
                subblockData = np.array(subblockData, dtype=np.float64)
            else:
                subblockData = np.array(subblockData, dtype=np.float32)
            outputSignal[i] = compute_statistic(subblockData, statisticsType)

    # Write header file
    headerFileName = f"staticRefCase{testId}.h"
    file_io.write_header_file(
        inputSignalFlat.tolist(),
        outputSignal.tolist(),
        testCase,
        headerFileName,
        outputBlockSize,
        outputNumChannels,
    )

    # Return min and max of output
    min_output = np.min(outputSignal) if outputSignal.size > 0 else 0.0
    max_output = np.max(outputSignal) if outputSignal.size > 0 else 0.0
    return [min_output, max_output]


