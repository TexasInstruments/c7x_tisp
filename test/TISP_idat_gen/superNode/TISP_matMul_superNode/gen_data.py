def get_soc_guard(am275_soc_value):
    """Generate SOC preprocessor guard based on 'AM275 SOC' column value.
    Excludes test cases from AM275 builds that exceed OCRAM limits."""
    if str(am275_soc_value).lower() != "yes":
        return "!(SOC == AM275 && !defined(HOST_EMULATION))"
    return None


def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testType = currPrm["testType"]
    dTypeIn = currPrm["dTypeIn"]
    dTypeOut = currPrm["dTypeOut"]
    m = currPrm["M"]
    n = currPrm["N"]
    k = currPrm["K"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]
    testId = currPrm["ID"]
    pitchA = currPrm["pitchA"]
    pitchB = currPrm["pitchB"]
    pitchOut = currPrm["pitchOut"]
    am275_soc = currPrm.get("AM275 SOC", "yes")

    if testType == "STATIC":
        inputDataA = "staticRefInACase" + testId
        inputDataB = "staticRefInBCase" + testId
        outputData = "staticRefOutCase" + testId

        # inputDataA = f'"{workDir}/bin/matrixA_{testId}.bin"'
        # inputDataB = f'"{workDir}/bin/matrixB_{testId}.bin"'
        # outputData = f'"{workDir}/bin/matrixOut_{testId}.bin"'
    else:
        inputDataA = "NULL"
        inputDataB = "NULL"
        outputData = "NULL"

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    soc_guard = get_soc_guard(am275_soc)
    if soc_guard:
        idatFile.write("#if %s\n" % soc_guard)

    DSPLIB_dTypeIn = TISP_utils.resolve_DSPLIB_dType(dTypeIn)
    if dTypeIn == "int8_t" or dTypeIn == "uint8_t":
        sizeBytes = 1
    elif dTypeIn == "int16_t" or dTypeIn == "uint16_t":
        sizeBytes = 2
    elif dTypeIn == "int32_t" or dTypeIn == "uint32_t" or dTypeIn == "float":
        sizeBytes = 4
    else:
        sizeBytes = 8

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Input vector A \n" % ((inputDataA)))
    idatFile.write("%s, // Input vector B \n" % ((inputDataB)))
    idatFile.write("%s, // Output vector \n" % ((outputData)))
    idatFile.write("%s, // datatype \n" % ((DSPLIB_dTypeIn)))
    idatFile.write("%s, // m \n" % ((m)))
    idatFile.write("%s, // n \n" % ((n)))
    idatFile.write("%s, // k \n" % ((k)))
    idatFile.write("%s, // dataPitchInA \n" % (pitchA))
    idatFile.write("%s, // dataPitchInB \n" % (pitchB))
    idatFile.write("%s, // dataPitchOut \n" % (pitchOut))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    if soc_guard:
        idatFile.write("#endif  // SOC guard\n")
    idatFile.write("#endif  // TEST_CASE guard")
    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "TISP_matMul_superNode_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            am275_soc = testCase.get("AM275 SOC", "yes")
            soc_guard = get_soc_guard(am275_soc)
            if soc_guard:
                testId = testCase["ID"]
                demoCase = testCase.get("demoCase", "False")
                if demoCase == "true":
                    idatFile.write(
                        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
                        % (int(testId))
                    )
                else:
                    idatFile.write(
                        "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n"
                        % (int(testId))
                    )
                idatFile.write("#if %s\n" % soc_guard)
                idatFile.write('#include "test_data/staticRefCase%s.h"\n' % str(testId))
                idatFile.write("#endif  // SOC guard\n")
                idatFile.write("#endif\n\n")
            else:
                TISP_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static TISP_matMul_superNode_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["M"] = int(testCase["M"])
    testCase["N"] = int(testCase["N"])
    testCase["K"] = int(testCase["K"])
    testCase["pitchA"] = int(testCase["pitchA"])
    testCase["pitchB"] = int(testCase["pitchB"])
    testCase["pitchOut"] = int(testCase["pitchOut"])

    return testCase


