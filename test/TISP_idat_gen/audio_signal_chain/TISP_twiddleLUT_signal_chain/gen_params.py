#!/usr/bin/env python3
"""Generate TISP_twiddleLUT_signal_chain_params.h from test_cases.json.

Usage:
    python3 gen_params.py

Reads  : test_cases.json (same directory as this script)
Writes : ../../../audio_signal_chain/TISP_twiddleLUT_signal_chain/
             TISP_twiddleLUT_signal_chain_params.h
"""

import json
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.join(SCRIPT_DIR, "test_cases.json")
OUTPUT_PATH = os.path.join(
    SCRIPT_DIR,
    "..",
    "..",
    "..",
    "audio_signal_chain",
    "TISP_twiddleLUT_signal_chain",
    "TISP_twiddleLUT_signal_chain_params.h",
)

MAX_SUBGRAPHS = 4

TI_LICENSE = """\
"""


def main():
    with open(JSON_PATH, "r") as f:
        test_cases = json.load(f)

    num_tests = len(test_cases)
    output_path = os.path.normpath(OUTPUT_PATH)

    with open(output_path, "w") as out:
        out.write(TI_LICENSE)
        out.write("/* Auto-generated by gen_params.py -- do not hand-edit. */\n")
        out.write("#pragma once\n\n")
        out.write("#include <stdint.h>\n\n")
        out.write("#define MAX_SUBGRAPHS  (%d)\n" % MAX_SUBGRAPHS)
        out.write("#define NUM_TEST_CASES (%d)\n\n" % num_tests)
        out.write("typedef struct {\n")
        out.write("   uint32_t testID;\n")
        out.write("   uint32_t numSubgraphs;\n")
        out.write("   uint32_t fftSize[MAX_SUBGRAPHS];\n")
        out.write("   uint32_t numChannels[MAX_SUBGRAPHS];\n")
        out.write("} SubgraphTestParams_t;\n\n")
        out.write("static const SubgraphTestParams_t gTestParams[NUM_TEST_CASES] = {\n")

        for tc in test_cases:
            tid = tc["testID"]
            nsg = tc["numSubgraphs"]
            sizes = tc["fftSize"]
            channels = tc["numChannels"]

            # Pad to MAX_SUBGRAPHS with zeros
            sizes_padded = sizes + [0] * (MAX_SUBGRAPHS - len(sizes))
            channels_padded = channels + [0] * (MAX_SUBGRAPHS - len(channels))

            sizes_str = ", ".join("%5d" % s for s in sizes_padded)
            channels_str = ", ".join(str(c) for c in channels_padded)

            out.write(
                "   {%2d, %d, {%s}, {%s}},\n" % (tid, nsg, sizes_str, channels_str)
            )

        out.write("};\n")

    print("Generated %s with %d test cases" % (output_path, num_tests))


if __name__ == "__main__":
    main()
