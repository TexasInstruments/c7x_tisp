#!/usr/bin/env python3
"""
Signal Analyzer Script for Parametric EQ

This script provides functionality to:
1. Perform SNR analysis of all channels
2. Perform spectral analysis of a given channel

The script works with reference output files generated by parametric_eq.py,
which are stored in interleaved form where the first n samples correspond to
the sample 0 value of n channels.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy import signal
import argparse
import os
import sys

# Import from parametric_eq
from parametric_eq import plot_spectrum


def fancy_print_snr(pRef, pTest, numsamples, numchannels, mode="interleave"):
    """
    Calculate and fancy print SNR values on a per-channel basis.

    Parameters:
    -----------
    pRef : array-like
        Reference signal data
    pTest : array-like
        Test signal data
    numsamples : int
        Number of samples per channel
    numchannels : int
        Number of channels
    mode : str
        Data organization mode: 'interleave' or 'deinterleave' (default: 'interleave')
        - interleave: Data is organized as [ch0_s0, ch1_s0, ..., chN_s0, ch0_s1, ...]
        - deinterleave: Data is organized as [ch0_s0, ch0_s1, ..., ch0_sM, ch1_s0, ...]

    Returns:
    --------
    snr_values : ndarray
        Array of SNR values for each channel
    overall_snr : float
        Overall SNR across all channels
    """
    # Convert inputs to numpy arrays if they aren't already
    pRef = np.array(pRef)
    pTest = np.array(pTest)

    # Reshape data based on mode
    if mode.lower() == "interleave":
        # Reshape interleaved data to (samples, channels)
        ref_data = np.zeros((numsamples, numchannels), dtype=pRef.dtype)
        test_data = np.zeros((numsamples, numchannels), dtype=pTest.dtype)

        for i in range(len(pRef)):
            sample_idx = i // numchannels
            channel_idx = i % numchannels
            if sample_idx < numsamples:
                ref_data[sample_idx, channel_idx] = pRef[i]
                test_data[sample_idx, channel_idx] = pTest[i]

    elif mode.lower() == "deinterleave":
        # Reshape deinterleaved data to (samples, channels)
        ref_data = np.zeros((numsamples, numchannels), dtype=pRef.dtype)
        test_data = np.zeros((numsamples, numchannels), dtype=pTest.dtype)

        for ch in range(numchannels):
            start_idx = ch * numsamples
            end_idx = start_idx + numsamples
            ref_data[:, ch] = pRef[start_idx:end_idx]
            test_data[:, ch] = pTest[start_idx:end_idx]

    else:
        raise ValueError("Mode must be either 'interleave' or 'deinterleave'")

    # Calculate noise as the difference between test and reference
    noise_data = test_data - ref_data

    # Calculate signal power for each channel
    signal_power = np.mean(ref_data.astype("float64") ** 2, axis=0)

    # Calculate noise power for each channel
    noise_power = np.mean(noise_data.astype("float64") ** 2, axis=0)

    # Calculate SNR in dB for each channel
    snr_values = 10 * np.log10(signal_power / (noise_power + 1e-10))

    # Calculate overall SNR
    overall_signal_power = np.mean(ref_data.astype("float64") ** 2)
    overall_noise_power = np.mean(noise_data.astype("float64") ** 2)
    overall_snr = 10 * np.log10(overall_signal_power / (overall_noise_power + 1e-10))

    # Fancy print the results
    print("\n" + "=" * 60)
    print(f"{'SNR ANALYSIS RESULTS':^60}")
    print("=" * 60)
    print(f"{'Channel':<10}{'SNR (dB)':<15}{'Signal Power':<20}{'Noise Power':<15}")
    print("-" * 60)

    for ch in range(numchannels):
        print(
            f"{ch:<10}{snr_values[ch]:>12.2f} dB{signal_power[ch]:>18.2e}{noise_power[ch]:>15.2e}"
        )

    print("-" * 60)
    print(
        f"{'Overall':<10}{overall_snr:>12.2f} dB{overall_signal_power:>18.2e}{overall_noise_power:>15.2e}"
    )
    print("=" * 60 + "\n")

    return snr_values, overall_snr


def load_interleaved_data(filename, num_channels, num_samples=None):
    """
    Load interleaved data from a text file.

    Parameters:
    -----------
    filename : str
        Path to the input text file
    num_channels : int
        Number of audio channels
    num_samples : int, optional
        Number of samples per channel. If None, it will be calculated from the file size.

    Returns:
    --------
    data : ndarray
        Deinterleaved data with shape (samples, channels)
    """
    # Read all values from the file
    with open(filename, "r") as f:
        values = [int(line.strip()) for line in f if line.strip()]

    total_samples = len(values)

    # Calculate number of samples per channel if not provided
    if num_samples is None:
        if total_samples % num_channels != 0:
            raise ValueError(
                f"File contains {total_samples} values, which is not divisible by {num_channels} channels"
            )
        num_samples = total_samples // num_channels

    # Reshape the data to deinterleave it
    data = np.zeros((num_samples, num_channels), dtype=np.int32)

    for i in range(total_samples):
        sample_idx = i // num_channels
        channel_idx = i % num_channels
        if sample_idx < num_samples:
            data[sample_idx, channel_idx] = values[i]

    return data


def calculate_snr(signal_data, noise_data=None, reference_data=None):
    """
    Calculate Signal-to-Noise Ratio (SNR) in dB.

    Parameters:
    -----------
    signal_data : ndarray
        Signal data
    noise_data : ndarray, optional
        Noise data. If None, reference_data must be provided.
    reference_data : ndarray, optional
        Reference data. If provided, noise is calculated as (signal_data - reference_data).

    Returns:
    --------
    snr_db : float or ndarray
        SNR in dB. If input is multichannel, returns an array of SNR values for each channel.
    """
    if noise_data is None and reference_data is None:
        raise ValueError("Either noise_data or reference_data must be provided")

    if noise_data is None:
        # Calculate noise as the difference between signal and reference
        noise_data = signal_data - reference_data

    # Calculate signal power
    signal_power = np.mean(signal_data.astype("float64") ** 2, axis=0)

    # Calculate noise power
    noise_power = np.mean(noise_data.astype("float64") ** 2, axis=0)

    # Calculate SNR in dB
    snr_db = 10 * np.log10(signal_power / (noise_power + 1e-10))

    return snr_db


def analyze_snr(reference_file, test_file=None, num_channels=8):
    """
    Analyze SNR for all channels.

    Parameters:
    -----------
    reference_file : str
        Path to the reference output file
    test_file : str, optional
        Path to the test output file. If None, only the reference file statistics are shown.
    num_channels : int
        Number of audio channels

    Returns:
    --------
    snr_results : dict
        Dictionary containing SNR results
    """
    # Load reference data
    reference_data = load_interleaved_data(reference_file, num_channels)

    # Print statistics for reference data
    print(f"\nReference data statistics:")
    print(f"Shape: {reference_data.shape}")
    print(f"Range: [{np.min(reference_data)}, {np.max(reference_data)}]")

    # Calculate statistics per channel
    for ch in range(num_channels):
        ch_data = reference_data[:, ch]
        print(
            f"Channel {ch}: Mean = {np.mean(ch_data):.2f}, Std = {np.std(ch_data):.2f}, "
            f"Min = {np.min(ch_data)}, Max = {np.max(ch_data)}"
        )

    # If test file is provided, calculate SNR
    if test_file:
        # Load test data
        test_data = load_interleaved_data(test_file, num_channels)

        # Print statistics for test data
        print(f"\nTest data statistics:")
        print(f"Shape: {test_data.shape}")
        print(f"Range: [{np.min(test_data)}, {np.max(test_data)}]")

        # Calculate SNR for each channel
        snr_values = calculate_snr(test_data, reference_data=reference_data)

        print("\nSNR Analysis Results:")
        for ch in range(num_channels):
            print(f"Channel {ch}: SNR = {snr_values[ch]:.2f} dB")

        # Calculate overall SNR
        overall_snr = 10 * np.log10(
            np.mean(test_data.astype("float64") ** 2)
            / (
                np.mean(
                    (test_data.astype("float64") - reference_data.astype("float64"))
                    ** 2
                )
                + 1e-10
            )
        )
        print(f"Overall SNR: {overall_snr:.2f} dB")

        return {"per_channel_snr": snr_values, "overall_snr": overall_snr}

    return None


def perform_spectral_analysis(
    reference_file,
    test_file=None,
    num_channels=8,
    channel=0,
    fs=48000,
    fmin=20,
    fmax=10000,
    plot=True,
):
    """
    Perform spectral analysis on a specific channel.
    If both reference and test files are provided, their spectra will be overlaid.

    Parameters:
    -----------
    reference_file : str
        Path to the reference file
    test_file : str, optional
        Path to the test file. If provided, both spectra will be overlaid.
    num_channels : int
        Number of audio channels
    channel : int
        Channel to analyze
    fs : int
        Sampling frequency in Hz
    fmin : float
        Minimum frequency for the plot in Hz
    fmax : float
        Maximum frequency for the plot in Hz
    plot : bool
        Whether to display plots

    Returns:
    --------
    spectrum_data : dict
        Dictionary containing spectrum data
    """
    # Load reference data
    reference_data = load_interleaved_data(reference_file, num_channels)

    # Compute reference spectrum
    reference_spectrum = plot_spectrum(
        reference_data,
        fs,
        title=f"Spectral Analysis - Channel {channel}",
        channel=channel,
        fmin=fmin,
        fmax=fmax,
        enable_plotting=False,  # Don't plot yet
    )

    # If test file is provided, load and compute its spectrum
    if test_file:
        test_data = load_interleaved_data(test_file, num_channels)
        test_spectrum = plot_spectrum(
            test_data,
            fs,
            title="",  # Will be set in the combined plot
            channel=channel,
            fmin=fmin,
            fmax=fmax,
            enable_plotting=False,  # Don't plot yet
        )

        # Create combined plot if plotting is enabled
        if plot:
            plt.figure(figsize=(10, 6))

            # Get frequency and magnitude data
            f_ref = reference_spectrum["f"]
            X_db_ref = reference_spectrum["X_db"]
            f_test = test_spectrum["f"]
            X_db_test = test_spectrum["X_db"]

            # Plot only up to fmax
            mask_ref = (f_ref >= fmin) & (f_ref <= fmax)
            mask_test = (f_test >= fmin) & (f_test <= fmax)

            # Plot both spectra
            plt.semilogx(f_ref[mask_ref], X_db_ref[mask_ref], label="Reference")
            plt.semilogx(f_test[mask_test], X_db_test[mask_test], label="Test")

            plt.grid(True, which="both", ls="--", alpha=0.7)
            plt.xlabel("Frequency (Hz)")
            plt.ylabel("Magnitude (dB)")
            plt.title(f"Spectral Analysis - Channel {channel} - Reference vs Test")
            plt.xlim(fmin, fmax)
            plt.legend()

            plt.tight_layout()
            plt.show()

        return {
            "reference_spectrum": reference_spectrum,
            "test_spectrum": test_spectrum,
        }
    else:
        # If only reference file is provided, just plot its spectrum
        if plot:
            plt.figure(figsize=(10, 6))

            # Get frequency and magnitude data
            f = reference_spectrum["f"]
            X_db = reference_spectrum["X_db"]

            # Plot only up to fmax
            mask = (f >= fmin) & (f <= fmax)

            plt.semilogx(f[mask], X_db[mask], label="Reference")

            plt.grid(True, which="both", ls="--", alpha=0.7)
            plt.xlabel("Frequency (Hz)")
            plt.ylabel("Magnitude (dB)")
            plt.title(
                f"Spectral Analysis - Channel {channel} - File: {os.path.basename(reference_file)}"
            )
            plt.xlim(fmin, fmax)
            plt.legend()

            plt.tight_layout()
            plt.show()

        return {"reference_spectrum": reference_spectrum}


def main():
    """
    Main function to parse command line arguments and run the appropriate analysis.
    """
    parser = argparse.ArgumentParser(description="Signal Analyzer for Parametric EQ")

    # Common arguments
    parser.add_argument(
        "--reference", required=True, help="Path to the reference output file"
    )
    parser.add_argument(
        "--channels", type=int, default=8, help="Number of audio channels (default: 8)"
    )
    parser.add_argument(
        "--fs",
        type=int,
        default=48000,
        help="Sampling frequency in Hz (default: 48000)",
    )
    parser.add_argument("--no-plot", action="store_true", help="Disable plotting")

    # Subparsers for different analysis types
    subparsers = parser.add_subparsers(
        dest="analysis_type", help="Type of analysis to perform"
    )

    # SNR analysis subparser
    snr_parser = subparsers.add_parser("snr", help="Perform SNR analysis")
    snr_parser.add_argument("--test", help="Path to the test output file")

    # Spectral analysis subparser
    spectral_parser = subparsers.add_parser(
        "spectral", help="Perform spectral analysis"
    )
    spectral_parser.add_argument(
        "--test", help="Path to the test output file to overlay with reference"
    )
    spectral_parser.add_argument(
        "--channel", type=int, default=0, help="Channel to analyze (default: 0)"
    )
    spectral_parser.add_argument(
        "--fmin", type=float, default=20, help="Minimum frequency in Hz (default: 20)"
    )
    spectral_parser.add_argument(
        "--fmax",
        type=float,
        default=10000,
        help="Maximum frequency in Hz (default: 10000)",
    )

    args = parser.parse_args()

    # Check if reference file exists
    if not os.path.exists(args.reference):
        print(f"Error: Reference file '{args.reference}' not found.")
        return 1

    # Perform the requested analysis
    if args.analysis_type == "snr":
        if args.test and not os.path.exists(args.test):
            print(f"Error: Test file '{args.test}' not found.")
            return 1

        analyze_snr(args.reference, args.test, args.channels)

    elif args.analysis_type == "spectral":
        # Check if test file exists if provided
        if args.test and not os.path.exists(args.test):
            print(f"Error: Test file '{args.test}' not found.")
            return 1

        perform_spectral_analysis(
            args.reference,
            args.test,
            args.channels,
            args.channel,
            args.fs,
            args.fmin,
            args.fmax,
            not args.no_plot,
        )

    else:
        # If no analysis type is specified, show help
        parser.print_help()
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
