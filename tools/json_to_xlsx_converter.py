#!/usr/bin/env python3
"""
JSON to XLSX Converter for TISP Profiling Data

This script converts the JSON profiling data generated by NodeProfiler::writeJsonResults()
to an Excel (XLSX) file for easier analysis on x86 machines.

Usage:
    python json_to_xlsx_converter.py input.json [output.xlsx]

If output.xlsx is not specified, it will use the input filename with .xlsx extension.
"""

import json
import sys
import os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter


def format_header_row(sheet, row_num):
    """Format the header row with bold text and background color"""
    header_fill = PatternFill(
        start_color="DDEBF7", end_color="DDEBF7", fill_type="solid"
    )
    header_font = Font(bold=True)
    header_alignment = Alignment(horizontal="center", vertical="center")

    for cell in sheet[row_num]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = header_alignment


def auto_adjust_column_width(sheet):
    """Adjust column widths based on content"""
    for col in sheet.columns:
        max_length = 0
        column = col[0].column_letter
        for cell in col:
            if cell.value:
                try:
                    if len(str(cell.value)) > max_length:
                        max_length = len(str(cell.value))
                except:
                    pass
        adjusted_width = max_length + 2
        sheet.column_dimensions[column].width = adjusted_width


def add_borders(sheet, start_row, end_row, start_col, end_col):
    """Add borders to a range of cells"""
    thin_border = Border(
        left=Side(style="thin"),
        right=Side(style="thin"),
        top=Side(style="thin"),
        bottom=Side(style="thin"),
    )

    for row in range(start_row, end_row + 1):
        for col in range(start_col, end_col + 1):
            sheet.cell(row=row, column=col).border = thin_border


def json_to_xlsx(json_file, xlsx_file=None):
    """Convert JSON profiling data to XLSX format"""
    # If output file not specified, use input filename with .xlsx extension
    if xlsx_file is None:
        xlsx_file = os.path.splitext(json_file)[0] + ".xlsx"

    # Load JSON data
    with open(json_file, "r") as f:
        data = json.load(f)

    # Create a new workbook
    wb = Workbook()

    # Create Summary sheet
    summary_sheet = wb.active
    summary_sheet.title = "Summary"

    # Add summary data
    summary_sheet["A1"] = "TISP Profiling Summary"
    summary_sheet["A1"].font = Font(bold=True, size=14)

    summary_sheet["A3"] = "Metric"
    summary_sheet["B3"] = "Value"
    format_header_row(summary_sheet, 3)

    row = 4
    for key, value in data["summary"].items():
        # Convert snake_case to Title Case for display
        display_key = " ".join(word.capitalize() for word in key.split("_"))
        summary_sheet[f"A{row}"] = display_key
        summary_sheet[f"B{row}"] = value
        row += 1

    add_borders(summary_sheet, 3, row - 1, 1, 2)
    auto_adjust_column_width(summary_sheet)

    # Create Supernodes sheet
    if data["supernodes"]:
        supernodes_sheet = wb.create_sheet("Supernodes")

        # Add headers
        supernodes_sheet["A1"] = "Supernode ID"
        supernodes_sheet["B1"] = "Cycles"
        supernodes_sheet["C1"] = "Num Blocks"
        supernodes_sheet["D1"] = "Node Count"
        supernodes_sheet["E1"] = "Sum of Node Cycles"
        supernodes_sheet["F1"] = "Theoretical Total Cycles"
        supernodes_sheet["G1"] = "Efficiency"
        format_header_row(supernodes_sheet, 1)

        # Add supernode data
        row = 2
        for supernode in data["supernodes"]:
            # Basic supernode information
            supernode_id = supernode["id"]
            supernode_cycles = supernode["cycles"]
            node_count = len(supernode["nodes"])

            # Num blocks information (default to 1 if not present)
            num_blocks = supernode.get("num_blocks", 1)

            # Calculate sum of node cycles
            sum_node_cycles = sum(node["cycles"] for node in supernode["nodes"])

            # Calculate theoretical total cycles (num_blocks * sum_node_cycles)
            theoretical_cycles = num_blocks * sum_node_cycles

            # Calculate efficiency (actual cycles / theoretical cycles)
            # Higher than 1.0 means there's overhead
            # Lower than 1.0 would be unusual (might indicate parallelism or measurement issues)
            efficiency = (
                supernode_cycles / theoretical_cycles if theoretical_cycles > 0 else 0
            )

            # Add data to sheet
            supernodes_sheet[f"A{row}"] = supernode_id
            supernodes_sheet[f"B{row}"] = supernode_cycles
            supernodes_sheet[f"C{row}"] = num_blocks
            supernodes_sheet[f"D{row}"] = node_count
            supernodes_sheet[f"E{row}"] = sum_node_cycles
            supernodes_sheet[f"F{row}"] = theoretical_cycles
            supernodes_sheet[f"G{row}"] = f"{efficiency:.4f}"

            row += 1

        add_borders(supernodes_sheet, 1, row - 1, 1, 7)
        auto_adjust_column_width(supernodes_sheet)

    # Create appropriate node sheets based on whether supernodes exist
    if data["supernodes"]:
        # When supernodes exist, we don't create any additional node sheets
        # All node information is available in the individual supernode sheets
        pass
    else:
        # When no supernodes exist, create a single Nodes sheet with all nodes
        nodes_sheet = wb.create_sheet("Nodes")

        # Add header and total node time information
        nodes_sheet["A1"] = "Nodes"
        nodes_sheet["A1"].font = Font(bold=True, size=14)

        nodes_sheet["A3"] = "Total Node Time (cycles):"
        nodes_sheet["B3"] = data["summary"]["node_time_cycles"]
        nodes_sheet["A3"].font = Font(bold=True)

        # Add headers for nodes table
        nodes_sheet["A5"] = "Node ID"
        nodes_sheet["B5"] = "Node Name"
        nodes_sheet["C5"] = "Parameters"
        nodes_sheet["D5"] = "Cycles"
        nodes_sheet["E5"] = "% of Total Time"
        format_header_row(nodes_sheet, 5)

        # Add node data
        row = 6
        for node in data["nodes"]:
            node_cycles = node["cycles"]

            # Use node_id if available, otherwise use id
            if "node_id" in node:
                nodes_sheet[f"A{row}"] = node["node_id"]
            else:
                nodes_sheet[f"A{row}"] = node["id"]

            # Check if name field exists
            if "name" in node:
                nodes_sheet[f"B{row}"] = node["name"]
            else:
                nodes_sheet[f"B{row}"] = "Unknown"

            # Check if params field exists
            if "params" in node:
                nodes_sheet[f"C{row}"] = node["params"]
            else:
                nodes_sheet[f"C{row}"] = ""

            nodes_sheet[f"D{row}"] = node_cycles

            # Calculate percentage of total time
            percentage = (
                (node_cycles / data["summary"]["total_time_cycles"]) * 100
                if data["summary"]["total_time_cycles"] > 0
                else 0
            )
            nodes_sheet[f"E{row}"] = f"{percentage:.2f}%"

            row += 1

        add_borders(nodes_sheet, 5, row - 1, 1, 5)
        auto_adjust_column_width(nodes_sheet)

    # Create individual sheets for each supernode
    for supernode in data["supernodes"]:
        supernode_id = supernode["id"]
        sheet_name = f"Supernode_{supernode_id}"

        # Create a new sheet for this supernode
        supernode_sheet = wb.create_sheet(sheet_name)

        # Add supernode information at the top
        supernode_sheet["A1"] = f"Supernode {supernode_id} Details"
        supernode_sheet["A1"].font = Font(bold=True, size=14)

        # Basic supernode information
        supernode_sheet["A3"] = "Supernode ID:"
        supernode_sheet["B3"] = supernode_id
        supernode_sheet["A4"] = "Cycles:"
        supernode_sheet["B4"] = supernode["cycles"]

        # Num blocks information
        num_blocks = supernode.get("num_blocks", 1)
        supernode_sheet["A5"] = "Num Blocks:"
        supernode_sheet["B5"] = num_blocks

        # Node information
        supernode_sheet["A6"] = "Node Count:"
        supernode_sheet["B6"] = len(supernode["nodes"])

        # Calculate sum of node cycles
        sum_node_cycles = sum(node["cycles"] for node in supernode["nodes"])
        supernode_sheet["A7"] = "Sum of Node Cycles:"
        supernode_sheet["B7"] = sum_node_cycles

        # Calculate theoretical total cycles and efficiency
        theoretical_cycles = num_blocks * sum_node_cycles
        efficiency = (
            supernode["cycles"] / theoretical_cycles if theoretical_cycles > 0 else 0
        )
        supernode_sheet["A8"] = "Theoretical Total Cycles:"
        supernode_sheet["B8"] = theoretical_cycles
        supernode_sheet["A9"] = "Efficiency Ratio:"
        supernode_sheet["B9"] = f"{efficiency:.4f}"

        # Add headers for nodes table
        supernode_sheet["A11"] = "Node ID"
        supernode_sheet["B11"] = "Node Name"
        supernode_sheet["C11"] = "Parameters"
        supernode_sheet["D11"] = "Cycles"
        supernode_sheet["E11"] = "Total Cycles"
        supernode_sheet["F11"] = "% of Supernode Time"
        format_header_row(supernode_sheet, 11)

        # Add node data
        row = 12
        for node in supernode["nodes"]:
            node_id = node["id"]
            node_cycles = node["cycles"]
            percentage = (
                (node_cycles / supernode["cycles"]) * 100
                if supernode["cycles"] > 0
                else 0
            )

            # Use node_id if available, otherwise use id
            if "node_id" in node:
                supernode_sheet[f"A{row}"] = node["node_id"]
            else:
                supernode_sheet[f"A{row}"] = node_id

            # Check if name field exists
            if "name" in node:
                supernode_sheet[f"B{row}"] = node["name"]
            else:
                supernode_sheet[f"B{row}"] = "Unknown"

            # Check if params field exists
            if "params" in node:
                supernode_sheet[f"C{row}"] = node["params"]
            else:
                supernode_sheet[f"C{row}"] = ""

            # The node_cycles is already cycles per call
            supernode_sheet[f"D{row}"] = node_cycles

            # Calculate total cycles for this node (node_cycles * num_blocks)
            num_blocks = supernode.get("num_blocks", 1)
            total_node_cycles = node_cycles * num_blocks
            supernode_sheet[f"E{row}"] = total_node_cycles

            # Calculate percentage of supernode time using total node cycles
            percentage = (
                (total_node_cycles / supernode["cycles"]) * 100
                if supernode["cycles"] > 0
                else 0
            )
            supernode_sheet[f"F{row}"] = f"{percentage:.2f}%"
            row += 1

        add_borders(supernode_sheet, 11, row - 1, 1, 6)
        auto_adjust_column_width(supernode_sheet)

    # When supernodes exist, we only show nodes in their respective supernode sheets
    # When no supernodes exist, we show all nodes in a single Nodes sheet

    # Save the workbook
    wb.save(xlsx_file)
    print(f"Converted {json_file} to {xlsx_file}")
    return True


def main():
    """Main function to handle command line arguments"""
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} input.json [output.xlsx]")
        return 1

    json_file = sys.argv[1]
    xlsx_file = sys.argv[2] if len(sys.argv) > 2 else None

    if not os.path.exists(json_file):
        print(f"Error: Input file '{json_file}' not found.")
        return 1

    try:
        json_to_xlsx(json_file, xlsx_file)
        return 0
    except Exception as e:
        print(f"Error: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
